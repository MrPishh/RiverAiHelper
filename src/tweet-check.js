const { stripOfficialLinks } = require('./utils');

// ─── Rules ────────────────────────────────────────────────────────────────────

// X/Twitter status links: captures the account name in the link and the status ID.
const TWEET_LINK = /https?:\/\/(?:www\.)?(?:x|twitter)\.com\/([^\s/>)\\]+)\/status\/(\d+)/gi;
// Invites to another chat server — what the fake help-desk tweets link to.
const CHAT_INVITE = /(?:discord(?:app)?\.(?:gg|com\/invite)|dsc\.gg|t\.me|wa\.me)\/[\w-]+/i;
// Author names of fake help desks ("CREATE A TICKET", "Support Desk", "tcket00cx", "MOD| Live Chat"…).
const FAKE_DESK_NAME = /support|supp0rt|t[il]?[ck]+et|tiket|help ?desk|live ?chat|customer ?(care|service)|moderator/i;
// River's own X accounts: their posts are official, whatever they link to.
const OFFICIAL_HANDLES = /^(riverdotinc|river4fun)$/i;
// Links in a tweet's own text that don't point anywhere else (its own images and quoted posts).
const OWN_LINKS = /https?:\/\/(?:pic\.(?:x|twitter)\.com|(?:www\.)?(?:x|twitter)\.com)\/\S*/gi;

// How long a fetched tweet is reused, how long a fetch may take, and the pauses before each retry of a failed one.
const CACHE_MS   = 60 * 60 * 1000;
const TIMEOUT_MS = 6000;
const RETRY_DELAYS_MS = [1000, 3000];

// The status IDs a text links to (at most 3).
function tweetIds(text) {
    return [...new Set([...(text || '').matchAll(TWEET_LINK)].map(m => m[2]))].slice(0, 3);
}

// The account names written in a text's tweet links (x.com/<name>/status/…; "i" means no name given).
function linkHandles(text) {
    return [...(text || '').matchAll(TWEET_LINK)].map(m => m[1]).filter(h => h.toLowerCase() !== 'i');
}

// True when a message is little more than its links — no sentence of its own that the
// classifier should judge (mentions, emoji, dividers and up to two short words are allowed).
function isLinkOnly(text) {
    const rest = (text || '').replace(/https?:\/\/\S+/g, ' ').replace(/<[@#&!]*\d+>/g, ' ');
    return (rest.match(/\p{L}+/gu) ?? []).length <= 2;
}

// ─── Checker ──────────────────────────────────────────────────────────────────

// `fetchTweet(id)` and `retryDelaysMs` may be replaced in tests; by default it calls FxTwitter.
function createTweetChecker({ fetchTweet = fetchFromFxTwitter, retryDelaysMs = RETRY_DELAYS_MS } = {}) {
    const cache = new Map();   // id → { at, tweet }

    // One tweet, from the cache when fresh. Returns { name, handle, text, hasMedia, followers } or { error }.
    // A failed read is retried, then returned without being cached.
    async function getTweet(id) {
        const hit = cache.get(id);
        if (hit && Date.now() - hit.at < CACHE_MS) return hit.tweet;
        let tweet = await fetchTweet(id).catch(err => ({ error: err.message }));
        for (const delay of retryDelaysMs) {
            if (!tweet.error) break;
            await new Promise(resolve => setTimeout(resolve, delay));
            tweet = await fetchTweet(id).catch(err => ({ error: err.message }));
        }
        if (tweet.error) {
            console.warn(`[TweetCheck] Could not read tweet ${id} after ${retryDelaysMs.length + 1} attempts: ${tweet.error}`);
            return tweet;
        }
        if (cache.size > 500) cache.delete(cache.keys().next().value);
        cache.set(id, { at: Date.now(), tweet });
        return tweet;
    }

    // Judges every tweet a text links to. `campaign` maps status ID → how many different accounts
    // were already actioned for posting it. Returns null (no tweet links) or
    // { verdict: 'scam' | 'ordinary' | 'has-link' | 'unavailable', reason, tweets: [{ id, ...tweet }] }.
    // An 'unavailable' result has `deskHandle` when the link itself names a fake help-desk account.
    async function check(text, campaign = new Map()) {
        const ids = tweetIds(text);
        if (!ids.length) return null;
        const tweets = await Promise.all(ids.map(async id => ({ id, ...(await getTweet(id)) })));
        const isOfficial = t => OFFICIAL_HANDLES.test(t.handle || '');
        const known = tweets.find(t => !isOfficial(t) && (campaign.get(t.id) ?? 0) >= 2)?.id;
        if (known) return { verdict: 'scam', reason: `known campaign tweet (posted by ${campaign.get(known)} accounts before)`, tweets };
        const desk = tweets.find(t => !t.error && !isOfficial(t) &&
            (CHAT_INVITE.test(stripOfficialLinks(t.text)) || FAKE_DESK_NAME.test(`${t.name} ${t.handle}`)));
        if (desk) return { verdict: 'scam', reason: `fake help-desk tweet by ${desk.name} (@${desk.handle})`, tweets };
        if (tweets.some(t => t.error)) {
            const deskHandle = linkHandles(text).find(h => FAKE_DESK_NAME.test(h)) ?? null;
            return { verdict: 'unavailable', reason: 'linked tweet could not be read', deskHandle, tweets };
        }
        if (tweets.some(t => !isOfficial(t) && /https?:\/\//.test(stripOfficialLinks(t.text).replace(OWN_LINKS, '')))) {
            return { verdict: 'has-link', reason: 'linked tweet contains a link', tweets };
        }
        return { verdict: 'ordinary', reason: 'linked tweet is an ordinary post', tweets };
    }

    return { check };
}

// Fetches one tweet from FxTwitter. Throws on a timeout or network error.
async function fetchFromFxTwitter(id) {
    const fetch = (await import('node-fetch')).default;
    const res = await fetch(`https://api.fxtwitter.com/i/status/${id}`, {
        headers: { 'User-Agent': 'RiverAiHelper' },
        signal: AbortSignal.timeout(TIMEOUT_MS),
    });
    const j = await res.json().catch(() => ({}));
    const t = j.tweet;
    if (!t) return { error: j.message || `HTTP ${res.status}` };
    return { name: t.author?.name ?? '', handle: t.author?.screen_name ?? '', text: t.text ?? '', hasMedia: !!t.media?.all?.length, followers: t.author?.followers ?? null };
}

module.exports = { createTweetChecker, tweetIds, isLinkOnly };
