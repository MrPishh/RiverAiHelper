/* ─── About this file ─────────────────────────────────────────────────────────
 * Reads the X/Twitter posts a message links to and judges them for the scam
 * blocker. Tweets are fetched from FxTwitter's public API (no login, no key —
 * X's own embed service requires payment) and kept in memory for an hour; a
 * failed read is retried and never kept, so the next message tries again.
 * A tweet that is a fake help desk (a Discord/Telegram invite other than River's
 * own, or a "support"/"ticket" account) is scam; one with no link is an ordinary post;
 * one that can't be read is "unavailable" — the caller treats it as scam only when
 * the link's own account name looks like a fake help desk, else forwards it.
 * Exports: createTweetChecker, tweetIds, isLinkOnly
 * ────────────────────────────────────────────────────────────────────────── */

