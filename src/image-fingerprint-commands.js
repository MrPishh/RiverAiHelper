// ─── Setup ────────────────────────────────────────────────────────────────────

const {
    ApplicationCommandType, ApplicationCommandOptionType, PermissionFlagsBits, MessageFlags,
    ActionRowBuilder, ButtonBuilder, ButtonStyle, StringSelectMenuBuilder, EmbedBuilder, AttachmentBuilder,
} = require('discord.js');

// Name of the right-click (message context menu) command.
const MARK_COMMAND = 'Fingerprint scam images';

// Prefix of every button and menu ID this file owns.
const ID_PREFIX = 'scamimg';

// How long a confirmation screen stays usable.
const PENDING_MS = 15 * 60 * 1000;

// Sets shown per page of /scam-images action:List.
const LIST_PAGE_SIZE = 10;

// ─── Command definitions ──────────────────────────────────────────────────────

// Sent to Discord with the other commands (src/slash-commands.js COMMANDS). Hidden by default from members
// without Manage Messages; Server Settings → Integrations can give or take them per role.
const IMAGE_FINGERPRINT_COMMANDS = [
    {
        name: MARK_COMMAND,
        type: ApplicationCommandType.Message,
        default_member_permissions: String(PermissionFlagsBits.ManageMessages),
    },
    {
        name:        'scam-images',
        description: 'Fingerprinted scam images: list them, view one set, or remove a set or image',
        default_member_permissions: String(PermissionFlagsBits.ManageMessages),
        options: [
            {
                name:        'action',
                description: 'What to do',
                type:        ApplicationCommandOptionType.String,
                required:    true,
                choices: [
                    { name: 'List — every fingerprinted set',             value: 'list'   },
                    { name: 'View — one set, its images and remove buttons', value: 'view' },
                    { name: 'Remove — a whole set, or one image of it',   value: 'remove' },
                ],
            },
            { name: 'set',   description: 'Set number (View and Remove)', type: ApplicationCommandOptionType.Integer, required: false, min_value: 1 },
            { name: 'image', description: 'Remove only: one image number in the set (omit to remove the whole set)', type: ApplicationCommandOptionType.Integer, required: false, min_value: 1 },
        ],
    },
];

// Names of the commands handled here (the main slash handler skips them).
const IMAGE_FINGERPRINT_COMMAND_NAMES = new Set(IMAGE_FINGERPRINT_COMMANDS.map(c => c.name));

// ─── Interaction handler ──────────────────────────────────────────────────────

// Factory — returns the interactionCreate listener. `allowedRoleIds`: who may use these commands.
// `store` is src/image-fingerprints.js (swappable in tests).
function createImageFingerprintHandler({ allowedRoleIds, store }) {
    const allowed = new Set(allowedRoleIds);

    // Confirmation screens waiting for Save: token → { images, selected, source, userId, expires }.
    const pending = new Map();

    const ephemeral = { flags: MessageFlags.Ephemeral };
    // Who did something, as stored: { id, tag }.
    const who = (user) => ({ id: user.id, tag: user.tag ?? user.username });
    // True when the person has one of the allowed roles.
    const mayUse = (interaction) => interaction.member?.roles?.cache?.some?.(r => allowed.has(r.id)) ?? false;

    // One line describing a set, for the list and the view.
    function describeSet(set) {
        const inUse = set.images.filter(i => !i.removedAt).length;
        return `**#${set.id}** · ${inUse} image${inUse === 1 ? '' : 's'} · added ${set.createdAt} by <@${set.addedBy.id}>` +
            ` · ${set.matches} match${set.matches === 1 ? '' : 'es'}${set.lastMatchAt ? ` (last ${set.lastMatchAt})` : ''}`;
    }

    // ── Right-click → Fingerprint scam images ─────────────────────────────────
    // Downloads and fingerprints the message's images, then shows them with a pick list (2+ images) and Save/Cancel.
    async function startMarking(interaction) {
        const target = interaction.targetMessage;
        const found  = store.imageAttachments(target);
        if (!found.length) {
            await interaction.reply({ content: 'That message has no images to fingerprint.', ...ephemeral });
            return;
        }
        await interaction.deferReply(ephemeral);

        const images = [];
        const failed = [];
        for (const att of found.slice(0, 10)) {
            try {
                const buffer = await store.download(att.url, 50 * 1024 * 1024);
                const fp     = await store.fingerprint(buffer);
                images.push({ name: att.name, url: att.url, buffer, fp, already: store.findMatch(fp) });
            } catch (err) {
                console.warn(`[ScamImages] Could not read ${att.name}: ${err.message}`);
                failed.push(att.name);
            }
        }
        if (!images.length) {
            await interaction.editReply(`❌ Could not read the image${failed.length === 1 ? '' : 's'} in that message.`);
            return;
        }

        const token = interaction.id;
        pending.set(token, {
            images,
            selected: new Set(images.map((_, i) => i)),
            userId:   interaction.user.id,
            source:   {
                messageId: target.id, channelId: target.channelId,
                authorId: target.author?.id ?? null, authorTag: target.author?.tag ?? target.author?.username ?? null,
                content: target.content ?? '', postedAt: target.createdAt?.toISOString?.() ?? null,
            },
        });
        setTimeout(() => pending.delete(token), PENDING_MS).unref?.();

        const embeds = images.map((img, i) => {
            const notes = [];
            if (img.already) notes.push(`already fingerprinted — set #${img.already.setId}, image ${img.already.imageNo}`);
            if (img.fp.plain) notes.push('nearly one flat colour — will only match exact copies');
            return new EmbedBuilder()
                .setTitle(`Image ${i + 1} — ${img.name}`.slice(0, 256))
                .setDescription(notes.length ? notes.join('\n') : null)
                .setImage(img.url);
        });

        const rows = [];
        if (images.length > 1) {
            rows.push(new ActionRowBuilder().addComponents(
                new StringSelectMenuBuilder()
                    .setCustomId(`${ID_PREFIX}:pick:${token}`)
                    .setPlaceholder('Images to fingerprint')
                    .setMinValues(1)
                    .setMaxValues(images.length)
                    .addOptions(images.map((img, i) => ({ label: `Image ${i + 1} — ${img.name}`.slice(0, 100), value: String(i), default: true }))),
            ));
        }
        rows.push(new ActionRowBuilder().addComponents(
            new ButtonBuilder().setCustomId(`${ID_PREFIX}:save:${token}`).setLabel('Save fingerprints').setStyle(ButtonStyle.Success),
            new ButtonBuilder().setCustomId(`${ID_PREFIX}:cancel:${token}`).setLabel('Cancel').setStyle(ButtonStyle.Secondary),
        ));

        const intro = `**Fingerprint scam images** — message by <@${target.author?.id}> in <#${target.channelId}>\n` +
            (images.length > 1 ? 'Every image is ticked. Untick any that are not scam (a logo, a real announcement), then Save.\n' : 'Check the image, then Save.\n') +
            'After saving you can ban the sender; the same images are then blocked when anyone else posts them.' +
            (failed.length ? `\n⚠️ Could not read: ${failed.join(', ')}` : '');
        await interaction.editReply({ content: intro, embeds, components: rows, allowedMentions: { parse: [] } });
    }

    // The pick list changed: remember which images are ticked.
    async function pickImages(interaction, token) {
        const p = pending.get(token);
        if (!p) return interaction.update({ content: '⌛ This confirmation expired — right-click the message again.', embeds: [], components: [] });
        p.selected = new Set(interaction.values.map(Number));
        await interaction.deferUpdate();
    }

    // Save: stores the ticked images as one set.
    async function saveMarking(interaction, token) {
        const p = pending.get(token);
        if (!p) return interaction.update({ content: '⌛ This confirmation expired — right-click the message again.', embeds: [], components: [] });
        pending.delete(token);
        const chosen = p.images.filter((_, i) => p.selected.has(i));
        const set = store.addSet({
            images:  chosen.map(img => ({ name: img.name, buffer: img.buffer, fp: img.fp })),
            addedBy: who(interaction.user),
            source:  p.source,
        });
        console.log(`[ScamImages] Set #${set.id} saved by ${interaction.user.tag ?? interaction.user.id}: ${chosen.length} image(s) from message ${p.source.messageId}`);
        await interaction.update({
            content: `✅ Saved as **set #${set.id}** — ${chosen.length} image${chosen.length === 1 ? '' : 's'} at ${set.createdAt}.\n` +
                'You can ban the sender now. Anyone else posting these images is timed out and the message forwarded to #ai.\n' +
                `See it with \`/scam-images action:View set:${set.id}\`.`,
            embeds: [], components: [],
        });
    }

    // ── /scam-images ──────────────────────────────────────────────────────────

    // One page of the list, with Previous/Next buttons.
    function listPage(page) {
        const sets  = store.listSets();
        if (!sets.length) return { content: 'No fingerprinted scam images yet. Right-click a scam message → Apps → Fingerprint scam images.', embeds: [], components: [] };
        const pages = Math.ceil(sets.length / LIST_PAGE_SIZE);
        const p     = Math.min(Math.max(page, 0), pages - 1);
        const shown = sets.slice(p * LIST_PAGE_SIZE, (p + 1) * LIST_PAGE_SIZE);
        const embed = new EmbedBuilder()
            .setTitle(`Fingerprinted scam images — ${sets.length} set${sets.length === 1 ? '' : 's'}`)
            .setDescription(shown.map(describeSet).join('\n').slice(0, 4096))
            .setFooter({ text: `Page ${p + 1} of ${pages} · /scam-images action:View set:<number> to see one` });
        const components = pages > 1 ? [new ActionRowBuilder().addComponents(
            new ButtonBuilder().setCustomId(`${ID_PREFIX}:page:${p - 1}`).setLabel('Previous').setStyle(ButtonStyle.Secondary).setDisabled(p === 0),
            new ButtonBuilder().setCustomId(`${ID_PREFIX}:page:${p + 1}`).setLabel('Next').setStyle(ButtonStyle.Secondary).setDisabled(p >= pages - 1),
        )] : [];
        return { content: '', embeds: [embed], components };
    }

    // One set: its details, the saved image copies and a remove button for the set and for each image.
    function setView(set) {
        const inUse = set.images.filter(i => !i.removedAt);
        const files = inUse.map(img => new AttachmentBuilder(store.imagePath(set, img), { name: img.file }));
        const src   = set.source;
        const head  =
            `**Set #${set.id}** — ${describeSet(set).replace(/^\*\*#\d+\*\* · /, '')}\n` +
            `**Marked from:** message by <@${src.authorId}> (${src.authorTag ?? 'unknown'}) in <#${src.channelId}>${src.postedAt ? `, posted ${src.postedAt}` : ''}\n` +
            (src.content ? `**Text:** ${src.content.slice(0, 300)}\n` : '') +
            (set.lastMatch ? `**Last match:** <@${set.lastMatch.userId}> in <#${set.lastMatch.channelId}> at ${set.lastMatch.at}` : '');
        const embeds = inUse.map(img => new EmbedBuilder()
            .setTitle(`Image ${img.n} — ${img.name}`.slice(0, 256))
            .setDescription(`${img.matches} match${img.matches === 1 ? '' : 'es'}${img.lastMatchAt ? ` (last ${img.lastMatchAt})` : ''}${img.plain ? ' · exact copies only' : ''}`)
            .setImage(`attachment://${img.file}`));
        const buttons = [
            new ButtonBuilder().setCustomId(`${ID_PREFIX}:rmset:${set.id}`).setLabel('Remove whole set').setStyle(ButtonStyle.Danger),
            ...(inUse.length > 1 ? inUse.map(img => new ButtonBuilder().setCustomId(`${ID_PREFIX}:rmimg:${set.id}:${img.n}`).setLabel(`Remove image ${img.n}`).setStyle(ButtonStyle.Secondary)) : []),
        ];
        const components = [];
        for (let i = 0; i < buttons.length && components.length < 5; i += 5) components.push(new ActionRowBuilder().addComponents(buttons.slice(i, i + 5)));
        return { content: head.slice(0, 2000), embeds, files, components, allowedMentions: { parse: [] } };
    }

    // The reply after a removal.
    function removedReply(set, imageNo, by) {
        const what = imageNo ? `Image ${imageNo} of set #${set.id}` : `Set #${set.id}`;
        const also = imageNo && set.removedAt ? ` It was the last image, so set #${set.id} is removed too.` : '';
        return { content: `🗑️ ${what} removed at ${new Date().toISOString()} by <@${by.id}> — it no longer blocks anything.${also}\n` +
            'The record and image copies stay in data/scam-images/.', embeds: [], files: [], attachments: [], components: [], allowedMentions: { parse: [] } };
    }

    // /scam-images action:List | View | Remove.
    async function slashCommand(interaction) {
        const action = interaction.options.getString('action');
        const id     = interaction.options.getInteger('set');
        const imgNo  = interaction.options.getInteger('image');

        if (action === 'list') return interaction.reply({ ...listPage(0), ...ephemeral });

        if (!id) return interaction.reply({ content: `Please give a set number for ${action === 'view' ? 'View' : 'Remove'}.`, ...ephemeral });
        const set = store.getSet(id);
        if (!set || set.removedAt) return interaction.reply({ content: `There is no set #${id} in use.`, ...ephemeral });

        if (action === 'view') return interaction.reply({ ...setView(set), ...ephemeral });

        if (action === 'remove') {
            const by = who(interaction.user);
            const done = imgNo ? store.removeImage(id, imgNo, by) : store.removeSet(id, by);
            if (!done) return interaction.reply({ content: `Set #${id} has no image ${imgNo} in use.`, ...ephemeral });
            console.log(`[ScamImages] ${imgNo ? `Image ${imgNo} of set #${id}` : `Set #${id}`} removed by ${by.tag}`);
            return interaction.reply({ ...removedReply(done, imgNo, by), ...ephemeral });
        }
    }

    // A button or menu on one of the screens above.
    async function component(interaction) {
        const [, kind, a, b] = interaction.customId.split(':');
        if (kind === 'pick')   return pickImages(interaction, a);
        if (kind === 'save')   return saveMarking(interaction, a);
        if (kind === 'cancel') { pending.delete(a); return interaction.update({ content: 'Cancelled — nothing was saved.', embeds: [], components: [] }); }
        if (kind === 'page')   return interaction.update(listPage(Number(a)));
        if (kind === 'rmset' || kind === 'rmimg') {
            const by   = who(interaction.user);
            const done = kind === 'rmset' ? store.removeSet(a, by) : store.removeImage(a, b, by);
            if (!done) return interaction.update({ content: 'Already removed.', embeds: [], files: [], attachments: [], components: [] });
            console.log(`[ScamImages] ${kind === 'rmimg' ? `Image ${b} of set #${a}` : `Set #${a}`} removed by ${by.tag}`);
            return interaction.update(removedReply(done, kind === 'rmimg' ? b : null, by));
        }
    }

    // The interactionCreate listener. Ignores everything it doesn't own.
    return async function handleImageFingerprintInteraction(interaction) {
        const owns = ((interaction.isMessageContextMenuCommand?.() || interaction.isChatInputCommand?.()) && IMAGE_FINGERPRINT_COMMAND_NAMES.has(interaction.commandName))
            || ((interaction.isButton?.() || interaction.isStringSelectMenu?.()) && interaction.customId?.startsWith(`${ID_PREFIX}:`));
        if (!owns) return;
        try {
            if (!mayUse(interaction)) {
                await interaction.reply({ content: 'Only staff with the fingerprint role can use this.', ...ephemeral });
                return;
            }
            if (interaction.isMessageContextMenuCommand?.()) return await startMarking(interaction);
            if (interaction.isChatInputCommand?.())          return await slashCommand(interaction);
            return await component(interaction);
        } catch (err) {
            console.error('[ScamImages] Interaction failed:', err.message);
            try {
                if (interaction.deferred || interaction.replied) await interaction.followUp({ content: '❌ Something went wrong. Please try again.', ...ephemeral });
                else await interaction.reply({ content: '❌ Something went wrong. Please try again.', ...ephemeral });
            } catch {}
        }
    };
}

module.exports = { IMAGE_FINGERPRINT_COMMANDS, IMAGE_FINGERPRINT_COMMAND_NAMES, createImageFingerprintHandler };
