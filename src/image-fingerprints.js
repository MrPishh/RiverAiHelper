// ─── Setup ────────────────────────────────────────────────────────────────────

const fs     = require('fs');
const path   = require('path');
const crypto = require('crypto');
const sharp  = require('sharp');

// Where the fingerprints and the saved image copies live (data/ is never committed).
const ROOT_DIR   = path.join(__dirname, '..');
const STORE_DIR  = path.join(ROOT_DIR, 'data', 'scam-images');
const STORE_PATH = path.join(STORE_DIR, 'fingerprints.json');

// A near copy must pass both tests. Shape: the 64-bit perceptual hashes differ in at most PHASH_MAX_DISTANCE bits
// (measured 2026-11-20: resized, re-compressed, WebP/JPEG and slightly cropped copies 0–4; unrelated images about
// 30). Colour: the 4×4 colour grids differ by at most COLOR_MAX_DIFFERENCE on average (copies 0–5; the same layout
// in other colours 30+ — the hash is grey-only, so this is what tells those apart). Both are kept low on purpose:
// two different screenshots of the same app screen can sit close together.
const PHASH_MAX_DISTANCE   = 6;
const COLOR_MAX_DIFFERENCE = 12;

// Images bigger than this are not downloaded to be checked (scam images are small; this keeps the cost down).
const MAX_CHECK_BYTES = 20 * 1024 * 1024;

// File types treated as images. SVG is left out: it is code, not a picture.
const IMAGE_TYPE = /^image\/(?:png|jpe?g|webp|gif|bmp|tiff|avif|heic|heif)$/i;
const IMAGE_EXT  = /\.(?:png|jpe?g|webp|gif|bmp|tiff?|avif|heic|heif)$/i;

// ─── Fingerprints ─────────────────────────────────────────────────────────────

// Fingerprint of one image: an exact checksum, a 64-bit perceptual hash (pHash: the low frequencies of a 32×32 grey
// copy, which survive resizing and re-compression) and a 4×4 grid of its average colours. An animated image is read
// from its first frame. `plain`: the picture is nearly one flat colour, so its hash says little — such an image only
// ever matches an exact copy.
async function fingerprint(buffer) {
    const sha256 = crypto.createHash('sha256').update(buffer).digest('hex');
    // A fresh decode of the image on a white background (transparent parts become white).
    const open   = () => sharp(buffer, { limitInputPixels: 100e6 }).flatten({ background: '#ffffff' });
    const meta   = await sharp(buffer, { limitInputPixels: 100e6 }).metadata();
    const { data: grey } = await open().toColourspace('b-w').resize(32, 32, { fit: 'fill' }).raw().toBuffer({ resolveWithObject: true });
    const { data: grid } = await open().toColourspace('srgb').resize(4, 4, { fit: 'fill' }).raw().toBuffer({ resolveWithObject: true });

    // The 8×8 lowest DCT coefficients, each set to 1 when above the median (the DC term left out of the median).
    const coeffs = [];
    for (let u = 0; u < 8; u++) {
        for (let v = 0; v < 8; v++) {
            let sum = 0;
            for (let x = 0; x < 32; x++) {
                const cx = Math.cos(((2 * x + 1) * u * Math.PI) / 64);
                for (let y = 0; y < 32; y++) sum += grey[y * 32 + x] * cx * Math.cos(((2 * y + 1) * v * Math.PI) / 64);
            }
            coeffs.push(sum);
        }
    }
    const median = [...coeffs.slice(1)].sort((a, b) => a - b)[31];
    let bits = 0n;
    for (const c of coeffs) bits = (bits << 1n) | (c > median ? 1n : 0n);

    const values = [...grey.subarray(0, 1024)];
    const mean   = values.reduce((a, b) => a + b, 0) / values.length;
    const spread = Math.sqrt(values.reduce((a, b) => a + (b - mean) ** 2, 0) / values.length);
    return {
        sha256,
        phash:  bits.toString(16).padStart(16, '0'),
        colors: Buffer.from(grid.subarray(0, 48)).toString('hex'),
        width:  meta.width ?? null,
        height: meta.height ?? null,
        format: meta.format ?? null,
        plain:  spread < 2,
    };
}

// Number of bits that differ between two hex hashes.
function hammingDistance(a, b) {
    let x = BigInt(`0x${a}`) ^ BigInt(`0x${b}`);
    let n = 0;
    while (x) { n += Number(x & 1n); x >>= 1n; }
    return n;
}

// Average difference (0–255) between two colour grids.
function colorDifference(a, b) {
    const x = Buffer.from(a, 'hex'), y = Buffer.from(b, 'hex');
    let sum = 0;
    for (let i = 0; i < x.length; i++) sum += Math.abs(x[i] - y[i]);
    return sum / x.length;
}

// Downloads an image (Discord attachment URL). Refuses anything over `maxBytes`.
async function download(url, maxBytes = MAX_CHECK_BYTES) {
    const fetch = (await import('node-fetch')).default;
    const res = await fetch(url, { size: maxBytes, signal: AbortSignal.timeout(15000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return Buffer.from(await res.arrayBuffer());
}

// The image attachments of a Discord message, as { url, name, size } — its own and those of a message it forwards
// (Discord keeps a forward's attachments in messageSnapshots, not attachments).
function imageAttachments(message) {
    const forwarded = [...(message.messageSnapshots?.values?.() ?? [])].flatMap(s => [...(s.attachments?.values?.() ?? [])]);
    return [...(message.attachments?.values?.() ?? []), ...forwarded]
        .filter(a => a?.url && (IMAGE_TYPE.test(a.contentType ?? '') || (!a.contentType && IMAGE_EXT.test(a.name ?? ''))))
        .map(a => ({ url: a.url, name: a.name ?? 'image', size: a.size ?? null }));
}

// ─── Store ────────────────────────────────────────────────────────────────────

// Reads the whole store.
function load() {
    try { return JSON.parse(fs.readFileSync(STORE_PATH, 'utf8')); }
    catch { return { nextId: 1, sets: [] }; }
}

// Writes the whole store.
function save(store) {
    fs.mkdirSync(STORE_DIR, { recursive: true });
    fs.writeFileSync(STORE_PATH, JSON.stringify(store, null, 2), 'utf8');
}

// Images of a set that are still in use.
const activeImages = (set) => set.removedAt ? [] : set.images.filter(i => !i.removedAt);

// True when at least one fingerprinted image is in use (lets the message handler skip downloads otherwise).
function hasActiveFingerprints() {
    return load().sets.some(s => activeImages(s).length > 0);
}

// The closest image in use that `fp` matches, as { setId, imageNo, distance, exact }, or null. An exact copy
// always matches; a near copy only when neither image is plain.
function findMatch(fp) {
    let best = null;
    for (const set of load().sets) {
        for (const img of activeImages(set)) {
            if (img.sha256 === fp.sha256) return { setId: set.id, imageNo: img.n, distance: 0, exact: true };
            if (img.plain || fp.plain) continue;
            const distance = hammingDistance(img.phash, fp.phash);
            if (distance > PHASH_MAX_DISTANCE || colorDifference(img.colors, fp.colors) > COLOR_MAX_DIFFERENCE) continue;
            if (!best || distance < best.distance) {
                best = { setId: set.id, imageNo: img.n, distance, exact: false };
            }
        }
    }
    return best;
}

// Saves a new set: `images` is [{ name, buffer, fp }], `addedBy` { id, tag }, `source` the marked message
// ({ messageId, channelId, authorId, authorTag, content }). Copies of the images go in data/scam-images/set-N/.
// Returns the saved set.
function addSet({ images, addedBy, source }) {
    const store = load();
    const id    = store.nextId++;
    const dir   = path.join(STORE_DIR, `set-${id}`);
    fs.mkdirSync(dir, { recursive: true });
    const set = {
        id,
        createdAt: new Date().toISOString(),
        addedBy,
        source: { ...source, content: (source.content || '').slice(0, 500) },
        images: images.map((img, i) => {
            const n    = i + 1;
            const file = `image-${n}.${(img.fp.format || 'bin').replace('jpeg', 'jpg')}`;
            fs.writeFileSync(path.join(dir, file), img.buffer);
            const { sha256, phash, colors, width, height, format, plain } = img.fp;
            return { n, name: img.name, file, sha256, phash, colors, width, height, format, plain, matches: 0, lastMatchAt: null };
        }),
        matches: 0,
        lastMatchAt: null,
        removedAt: null,
        removedBy: null,
    };
    store.sets.push(set);
    save(store);
    return set;
}

// Every set, newest first. Removed sets are left out unless `includeRemoved`.
function listSets({ includeRemoved = false } = {}) {
    return load().sets.filter(s => includeRemoved || !s.removedAt).sort((a, b) => b.id - a.id);
}

// One set by ID, or null (removed sets included).
function getSet(id) {
    return load().sets.find(s => s.id === Number(id)) ?? null;
}

// Marks a whole set as removed, so it no longer matches. Returns the set, or null if there is none in use.
function removeSet(id, removedBy) {
    const store = load();
    const set = store.sets.find(s => s.id === Number(id));
    if (!set || set.removedAt) return null;
    set.removedAt = new Date().toISOString();
    set.removedBy = removedBy;
    save(store);
    return set;
}

// Marks one image of a set as removed. When it was the last one in use, the set is removed too.
// Returns the set, or null if there is no such image in use.
function removeImage(id, imageNo, removedBy) {
    const store = load();
    const set = store.sets.find(s => s.id === Number(id));
    const img = set && !set.removedAt ? set.images.find(i => i.n === Number(imageNo) && !i.removedAt) : null;
    if (!img) return null;
    const now = new Date().toISOString();
    img.removedAt = now;
    img.removedBy = removedBy;
    if (!activeImages(set).length) { set.removedAt = now; set.removedBy = removedBy; }
    save(store);
    return set;
}

// Counts a match against a set and its image, and notes what matched.
function recordMatch(setId, imageNo, { userId, messageId, channelId }) {
    const store = load();
    const set = store.sets.find(s => s.id === Number(setId));
    if (!set) return;
    const now = new Date().toISOString();
    set.matches += 1;
    set.lastMatchAt = now;
    set.lastMatch = { userId, messageId, channelId, at: now };
    const img = set.images.find(i => i.n === Number(imageNo));
    if (img) { img.matches += 1; img.lastMatchAt = now; }
    save(store);
}

// Full path of a saved image copy.
function imagePath(set, img) {
    return path.join(STORE_DIR, `set-${set.id}`, img.file);
}

