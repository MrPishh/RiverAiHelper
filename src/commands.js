    // A question deleted before it was answered no longer needs an answer — the asker removed it,
    // or a moderator, AutoMod or the scam blocker did. It is taken out of its pending batch, and
    // the batch is dropped when nothing is left.
    discordClient.on('messageDelete', (deleted) => {
        const key = state.pendingMsgIndex.get(deleted.id);
        if (!key) return;
        state.pendingMsgIndex.delete(deleted.id);
        const pending = state.pendingQuestions.get(key);
        if (!pending) return;
        pending.messages = pending.messages.filter(m => m.id !== deleted.id);
        if (pending.messages.length === 0) {
            cancelPendingBatch(key);
            console.log(`[AutoAnswer] Dropped pending answer for ${pending.userId} — the question was deleted`);
        } else if (pending.lastMessage?.id === deleted.id) {
            pending.lastMessageDeleted = true;
        }
    });

