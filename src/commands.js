    // ─── Scam blocker ─────────────────────────────────────────────────────────
    // Deletes the message, issues an escalating timeout (1 hour × the user's infraction count,
    // capped at 28 days), and posts an alert embed.
    // No-ops silently when the scam-blocker toggle is OFF — detection still logs.

    const SCAM_TIMEOUT_BASE_MS = 60 * 60 * 1000; // 1 hour — base unit for escalation
    const SCAM_TIMEOUT_MAX_MS  = 28 * 24 * 60 * 60 * 1000; // 28 days — Discord hard cap

    // Timeout for the Nth infraction: N hours, capped at 28 days.
    function escalatedTimeoutMs(nextCount) {
        return Math.min(nextCount * SCAM_TIMEOUT_BASE_MS, SCAM_TIMEOUT_MAX_MS);
    }

    // Human-readable timeout length, e.g. "3h timeout" or "1d 2h timeout".
    function formatTimeoutLabel(ms) {
        const totalHours = Math.round(ms / SCAM_TIMEOUT_BASE_MS);
        if (totalHours < 24) return `${totalHours}h timeout`;
        const days  = Math.floor(totalHours / 24);
        const hours = totalHours % 24;
        return hours > 0 ? `${days}d ${hours}h timeout` : `${days}d timeout`;
    }

    // Who wrote a replied-to message and its first 300 characters, for the evidence record.
    function describeReply(ref) {
        return { authorId: ref.author?.id ?? null, tag: ref.author?.tag ?? ref.author?.username ?? null, content: (ref.content || '').slice(0, 300) };
    }

    // What a scam review needs beyond the text, read from the message without any API call:
    // the message it replied to (when cached), its attachments, and the link previews Discord
    // attached (for an X link, usually the tweet's author and text).
    function scamEvidence(message) {
        const repliedToId = message.reference?.messageId ?? null;
        const cached      = repliedToId ? message.channel?.messages?.cache?.get(repliedToId) : null;
        return {
            repliedToId,
            repliedTo:   cached ? describeReply(cached) : null,
            attachments: [...(message.attachments?.values?.() ?? [])].map(a => ({ name: a.name, type: a.contentType ?? null })),
            previews:    (message.embeds ?? []).map(e => ({ url: e.url ?? null, title: e.title ?? null, author: e.author?.name ?? null, text: (e.description || '').slice(0, 300) })),
        };
    }

