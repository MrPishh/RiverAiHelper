const fs   = require('fs');
const path = require('path');

// ─── Setup ────────────────────────────────────────────────────────────────────

// Project root, settings and the Anthropic client.
const ROOT = path.join(__dirname, '..', '..');
require('dotenv').config({ path: path.join(ROOT, '.env'), quiet: true });
const Anthropic = require('@anthropic-ai/sdk');

// Model, how many requests run at once, and where the results go.
const MODEL       = 'claude-sonnet-4-6';
const CONCURRENCY = 5;
const OUT_PATH    = path.join(ROOT, 'data', `scam-review-${new Date().toISOString().slice(0, 10)}.json`);

// ─── Prompt ───────────────────────────────────────────────────────────────────

// The review instructions: the taxonomy's scam-related rules plus the verdict format.
function buildSystemPrompt() {
    const taxonomy = fs.readFileSync(path.join(ROOT, 'intent', 'intent-taxonomy.md'), 'utf8');
    return 'You review messages that a Discord support bot deleted as scam (the sender was also timed out). ' +
        'Decide whether each deletion was correct, using these classification rules for a crypto project community:\n\n' +
        `${taxonomy}\n\n---\n\n` +
        'You only see the message text — no images, no surrounding conversation. Strong criticism, FUD, insults or sharing an ordinary ' +
        'link (e.g. a tweet) are NOT scam on their own; scam means trying to lure people off-channel, to DMs, to external "support", ' +
        'or to wallet/connect/claim sites, or impersonating staff. If the text alone cannot settle it, say UNSURE.\n\n' +
        'Reply in exactly one line:\nVERDICT: SCAM | REASON: <short reason>\nor\nVERDICT: NOT_SCAM | REASON: <short reason>\nor\nVERDICT: UNSURE | REASON: <short reason>';
}

// Parses the model's one-line verdict.
function parseVerdict(text) {
    const m = text.trim().match(/VERDICT:\s*(SCAM|NOT_SCAM|UNSURE)\s*\|\s*REASON:\s*(.+)/is);
    return m ? { verdict: m[1].toUpperCase(), reason: m[2].trim() } : { verdict: 'UNPARSEABLE', reason: text.trim().slice(0, 200) };
}

// ─── Review ───────────────────────────────────────────────────────────────────

// Every recorded infraction (since `since`, if given) as a review item.
function collectItems(since) {
    const store = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'scammer-list.json'), 'utf8'));
    const items = [];
    for (const user of Object.values(store)) {
        for (const [i, inf] of user.infractions.entries()) {
            if (since && new Date(inf.ts) < since) continue;
            items.push({ userId: user.userId, tag: user.tag, infraction: i + 1, ts: inf.ts, detection: inf.reason, channelId: inf.channelId, actions: inf.actions, content: inf.content || '' });
        }
    }
    return items;
}

// Asks the model about each item and returns one result row per item.
async function review(items) {
    const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
    const system = [{ type: 'text', text: buildSystemPrompt(), cache_control: { type: 'ephemeral' } }];
    const results = new Array(items.length);
    let next = 0, done = 0;
    // One worker: takes the next unreviewed item until none are left.
    async function worker() {
        while (next < items.length) {
            const idx = next++;
            const it = items[idx];
            // Up to 3 attempts with growing waits — busy/overloaded API errors are usually temporary.
            for (let attempt = 1; attempt <= 3; attempt++) {
                try {
                    const resp = await anthropic.messages.create({
                        model: MODEL, max_tokens: 120, system,
                        messages: [{ role: 'user', content: `Detected by: ${it.detection}\nMessage text:\n"""${it.content || '(empty — e.g. an image or link preview only)'}"""` }],
                    });
                    results[idx] = { ...it, ...parseVerdict(resp.content[0].text) };
                    break;
                } catch (err) {
                    results[idx] = { ...it, verdict: 'ERROR', reason: err.message };
                    if (attempt < 3) await new Promise(r => setTimeout(r, 5000 * attempt));
                }
            }
            if (++done % 50 === 0) console.log(`  reviewed ${done}/${items.length}`);
        }
    }
    await Promise.all(Array.from({ length: CONCURRENCY }, worker));
    return results;
}

// ─── Main ─────────────────────────────────────────────────────────────────────

// Writes the cases a person should check (not scam, unsure, errors) to a CSV next to the results,
// with empty "your_label" / "your_note" columns: label each row scam, spam or fine. Opens in Excel.
function exportToCheck(results, jsonPath) {
    const rows = results.filter(r => r.verdict !== 'SCAM');
    const q = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
    const head = ['row', 'date', 'user_id', 'user_tag', 'infraction_no', 'channel_id', 'detection', 'ai_verdict', 'ai_reason', 'message', 'your_label (scam / spam / fine)', 'your_note'];
    const lines = rows.map((r, i) => [i + 1, r.ts, r.userId, r.tag, r.infraction, r.channelId, r.detection, r.verdict, r.reason, r.content, '', ''].map(q).join(','));
    const csvPath = jsonPath.replace(/\.json$/, '-to-check.csv');
    fs.writeFileSync(csvPath, '﻿' + [head.map(q).join(','), ...lines].join('\r\n'), 'utf8');
    return { csvPath, count: rows.length };
}

(async () => {
    const retryAt = process.argv.indexOf('--retry-errors');
    const at = process.argv.indexOf('--since');
    let results, outPath = OUT_PATH;
    if (retryAt !== -1) {
        // Re-review only the rows that failed last time, in an existing results file.
        outPath = path.resolve(process.argv[retryAt + 1]);
        results = JSON.parse(fs.readFileSync(outPath, 'utf8'));
        const failedIdx = results.map((r, i) => (r.verdict === 'ERROR' || r.verdict === 'UNPARSEABLE' ? i : -1)).filter(i => i >= 0);
        console.log(`Re-reviewing ${failedIdx.length} row(s) that failed before`);
        const redone = await review(failedIdx.map(i => results[i]));
        failedIdx.forEach((idx, k) => { results[idx] = redone[k]; });
    } else {
        const since = at !== -1 ? new Date(process.argv[at + 1]) : null;
        results = await review(collectItems(since));
    }
    fs.writeFileSync(outPath, JSON.stringify(results, null, 2), 'utf8');
    const exported = exportToCheck(results, outPath);
    const count = (v) => results.filter(r => r.verdict === v).length;
    console.log(`\nResults: ${results.length} action(s): ` +
        `SCAM ${count('SCAM')} · NOT_SCAM ${count('NOT_SCAM')} · UNSURE ${count('UNSURE')} · errors ${count('ERROR') + count('UNPARSEABLE')}`);
    console.log(`Full results (with message text): ${path.relative(ROOT, outPath)}`);
    console.log(`To check (${exported.count} rows, label each scam / spam / fine): ${path.relative(ROOT, exported.csvPath)}`);
    for (const r of results.filter(r => r.verdict === 'NOT_SCAM' || r.verdict === 'UNSURE')) {
        console.log(`  ${r.verdict.padEnd(8)} ${r.ts.slice(0, 10)} user ${r.userId} (infraction #${r.infraction}, ${r.detection}) — ${r.reason}`);
    }
})().catch(err => { console.error('review failed:', err.message); process.exit(1); });
