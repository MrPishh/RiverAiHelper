const fs   = require('fs');
const path = require('path');

// ─── Setup ────────────────────────────────────────────────────────────────────

// Project root, settings and the Anthropic client.
const ROOT = path.join(__dirname, '..', '..');
require('dotenv').config({ path: path.join(ROOT, '.env'), quiet: true });
const Anthropic = require('@anthropic-ai/sdk');

// Model, how many requests run at once, and where the results go.
const MODEL       = 'claude-sonnet-4-6';
const CONCURRENCY = 5;
const OUT_PATH    = freshPath(path.join(ROOT, 'data', `scam-review-${new Date().toISOString().slice(0, 10)}.json`));

// `file`, or file-2, file-3… if it exists — a second run on the same day never overwrites an earlier one.
function freshPath(file) {
    let n = 1, candidate = file;
    while (fs.existsSync(candidate)) candidate = file.replace(/\.json$/, `-${++n}.json`);
    return candidate;
}

// ─── Prompt ───────────────────────────────────────────────────────────────────

// The review instructions: the taxonomy's scam-related rules plus the verdict format.
function buildSystemPrompt() {
    const taxonomy = fs.readFileSync(path.join(ROOT, 'intent', 'intent-taxonomy.md'), 'utf8');
    return 'You review messages that a Discord support bot deleted as scam (the sender was also timed out). ' +
        'Decide whether each deletion was correct, using these classification rules for a crypto project community:\n\n' +
        `${taxonomy}\n\n---\n\n` +
        'Besides the text you may get context lines: "Same link posted by N different accounts" (one link posted by many accounts ' +
        'is a coordinated campaign), "Tweet:" (what a linked X/Twitter post actually says, its author and follower count, fetched ' +
        'afterwards; "no longer available" usually means deleted or suspended), "Replied to:", "Attachments:" and "Link preview:". ' +
        'Strong criticism, FUD, insults or sharing an ordinary tweet are NOT scam on their own; scam means trying to lure people ' +
        'off-channel, to DMs, to external "support" (e.g. a tweet that is a "create a ticket" Discord invite), or to ' +
        'wallet/connect/claim sites, or impersonating staff. If the evidence cannot settle it, say UNSURE.\n\n' +
        'Reply in exactly one line:\nVERDICT: SCAM | REASON: <short reason>\nor\nVERDICT: NOT_SCAM | REASON: <short reason>\nor\nVERDICT: UNSURE | REASON: <short reason>';
}

// Parses the model's one-line verdict.
function parseVerdict(text) {
    const m = text.trim().match(/VERDICT:\s*(SCAM|NOT_SCAM|UNSURE)\s*\|\s*REASON:\s*(.+)/is);
    return m ? { verdict: m[1].toUpperCase(), reason: m[2].trim() } : { verdict: 'UNPARSEABLE', reason: text.trim().slice(0, 200) };
}

// ─── Review ───────────────────────────────────────────────────────────────────

// Every recorded infraction (since `since`, if given) as a review item.
function collectItems(since) {
    const store = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'scammer-list.json'), 'utf8'));
    const items = [];
    for (const user of Object.values(store)) {
        for (const [i, inf] of user.infractions.entries()) {
            if (since && new Date(inf.ts) < since) continue;
            items.push({ userId: user.userId, tag: user.tag, infraction: i + 1, ts: inf.ts, detection: inf.reason, channelId: inf.channelId, actions: inf.actions, content: inf.content || '', evidence: inf.evidence ?? null });
        }
    }
    return items;
}

// ─── Context ──────────────────────────────────────────────────────────────────

// X/Twitter status links in a text, as [handle, statusId] pairs.
function tweetLinks(text) {
    return [...(text || '').matchAll(/https?:\/\/(?:x|twitter)\.com\/([^\s/>)\\]+)\/status\/(\d+)/gi)].map(m => [m[1], m[2]]);
}

// How many different accounts posted each tweet, across every recorded infraction (keyed by
// status ID, so x.com/i/status/N and x.com/name/status/N count as one tweet).
function campaignCounts() {
    const store = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'scammer-list.json'), 'utf8'));
    const posters = new Map();
    for (const user of Object.values(store)) {
        for (const inf of user.infractions) {
            for (const [, id] of tweetLinks(inf.content)) {
                if (!posters.has(id)) posters.set(id, new Set());
                posters.get(id).add(user.userId);
            }
        }
    }
    return posters;
}

// Fetches what each linked tweet says from FxTwitter's public API (no login, no key — X's own
// embed service now requires payment). Results are kept in data/scam-review-tweets.json, so a
// tweet is fetched once; failed lookups other than "not found" are retried next run.
async function fetchTweets(items) {
    const cachePath = path.join(ROOT, 'data', 'scam-review-tweets.json');
    const cache = fs.existsSync(cachePath) ? JSON.parse(fs.readFileSync(cachePath, 'utf8')) : {};
    const ids = [...new Set(items.flatMap(it => tweetLinks(it.content).map(([, id]) => id)))]
        .filter(id => !cache[id] || (cache[id].error && cache[id].error !== 'NOT_FOUND'));
    for (const id of ids) {
        try {
            const res = await fetch(`https://api.fxtwitter.com/i/status/${id}`, { signal: AbortSignal.timeout(15000) });
            const j = await res.json().catch(() => ({}));
            const t = j.tweet;
            cache[id] = t
                ? { name: t.author?.name, handle: t.author?.screen_name, text: t.text, hasMedia: !!t.media?.all?.length, followers: t.author?.followers }
                : { error: j.message || `HTTP ${res.status}` };
        } catch (err) { cache[id] = { error: err.message }; }
        await new Promise(r => setTimeout(r, 400));
    }
    fs.writeFileSync(cachePath, JSON.stringify(cache, null, 2));
    if (ids.length) console.log(`Fetched ${ids.length} tweet(s) for context`);
    return cache;
}

// The context lines added under a message for the reviewer.
function contextLines(it, posters, tweets) {
    const lines = [];
    for (const [, id] of tweetLinks(it.content).slice(0, 2)) {
        const n = posters.get(id)?.size ?? 0;
        if (n >= 2) lines.push(`Same link posted by ${n} different accounts`);
        const t = tweets[id];
        if (t?.error) lines.push('Tweet: no longer available');
        else if (t) lines.push(`Tweet: ${t.name} (@${t.handle}, ${t.followers} followers): "${t.text}"${t.hasMedia ? ' [+ image]' : ''}`);
    }
    const ev = it.evidence;
    if (ev?.repliedTo) lines.push(`Replied to: "${ev.repliedTo.content}"`);
    if (ev?.attachments?.length) lines.push(`Attachments: ${ev.attachments.map(a => a.type || a.name).join(', ')}`);
    for (const p of ev?.previews ?? []) lines.push(`Link preview: ${[p.author, p.title, p.text].filter(Boolean).join(' — ')}`);
    return lines;
}

// Asks the model about each item and returns one result row per item.
async function review(items) {
    const posters = campaignCounts();
    const tweets  = await fetchTweets(items);
    const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
    const system = [{ type: 'text', text: buildSystemPrompt(), cache_control: { type: 'ephemeral' } }];
    const results = new Array(items.length);
    let next = 0, done = 0;
    // One worker: takes the next unreviewed item until none are left.
    async function worker() {
        while (next < items.length) {
            const idx = next++;
            const it = items[idx];
            // Up to 3 attempts with growing waits — busy/overloaded API errors are usually temporary.
            for (let attempt = 1; attempt <= 3; attempt++) {
                try {
                    const resp = await anthropic.messages.create({
                        model: MODEL, max_tokens: 120, system,
                        messages: [{ role: 'user', content: `Detected by: ${it.detection}\nMessage text:\n"""${it.content || '(empty — e.g. an image or link preview only)'}"""` +
                            contextLines(it, posters, tweets).map(l => `\n${l}`).join('') }],
                    });
                    results[idx] = { ...it, ...parseVerdict(resp.content[0].text) };
                    break;
                } catch (err) {
                    results[idx] = { ...it, verdict: 'ERROR', reason: err.message };
                    if (attempt < 3) await new Promise(r => setTimeout(r, 5000 * attempt));
                }
            }
            if (++done % 50 === 0) console.log(`  reviewed ${done}/${items.length}`);
        }
    }
    await Promise.all(Array.from({ length: CONCURRENCY }, worker));
    return results;
}

