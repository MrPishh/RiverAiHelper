/* ─── About this file ─────────────────────────────────────────────────────────
 * Periodic AI review of scam-blocker actions: sends every recorded infraction in
 * data/scammer-list.json (or only those since a date) to Sonnet with the scam
 * rules from intent/intent-taxonomy.md, and asks whether it really was scam.
 * Writes the full results — including message text — to
 * data/scam-review-<date>.json (local only, never committed) and prints counts
 * plus the cases to check. Use it to find false positives and refine the rules.
 * Run: node scripts/scam-review/review-infractions.js [--since YYYY-MM-DD]
 *      node scripts/scam-review/review-infractions.js --retry-errors data/scam-review-<date>.json
 * Costs roughly $1–4 per 500 messages. Never changes the scammer list.
 * ─────────────────────────────────────────────────────────────────────────── */

