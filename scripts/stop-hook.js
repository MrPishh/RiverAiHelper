'use strict';

/* ─── About this file ─────────────────────────────────────────────────────────
 * Claude Code Stop hook (.claude/settings.json). When Claude is about to end a
 * turn: rebuild the index (shell edits skip the edit hook), then run
 * `build-index.js --check`; if the docs or index have drifted, send Claude
 * back once to fix them.
 *
 * Acts only when the code or docs changed since the last clean check — a
 * fingerprint of `git diff HEAD` and untracked files, limited to the paths the
 * builder indexes (never the bot's own data such as knowledge-base/ or logs),
 * kept in the git folder. Blocks at most once in a row: if drift remains after
 * one attempt (`stop_hook_active`), the turn ends and the user sees it.
 * Never fails a turn on its own errors.
 * ─────────────────────────────────────────────────────────────────────────── */

