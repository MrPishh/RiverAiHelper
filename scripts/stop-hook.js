const { execFileSync, spawnSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

// ─── Working-tree fingerprint ─────────────────────────────────────────────────

// Project root (the folder above scripts/).
const ROOT = path.join(__dirname, '..');

// Paths the builder indexes or checks — code, docs and the settings template.
const PATHSPEC = [
    'bot.js', 'src', 'telegram', 'intent', 'weekly-report', 'scripts', 'docs',
    ':(glob)*.md', 'package.json', '.env.example', '.claude/settings.json',
];

// Runs git in the project; returns its output, or null when git or the repository is unavailable.
function git(...args) {
    try {
        return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 });
    } catch {
        return null;
    }
}

// Hash of every indexed path that differs from HEAD (tracked diff + untracked names, sizes and times).
// Null outside git or before the first commit — then the check runs every time.
function fingerprint() {
    const diff = git('diff', 'HEAD', '--', ...PATHSPEC);
    const untracked = git('ls-files', '--others', '--exclude-standard', '--', ...PATHSPEC);
    if (diff === null || untracked === null) return null;
    const files = untracked.split('\n').filter(Boolean).map((f) => {
        try { const s = fs.statSync(path.join(ROOT, f)); return `${f}:${s.size}:${s.mtimeMs}`; } catch { return f; }
    });
    return crypto.createHash('sha256').update(diff).update(files.join('\n')).digest('hex');
}

// ─── Hook ─────────────────────────────────────────────────────────────────────

// Answers Claude Code (JSON on stdout) and ends the process.
function reply(obj) {
    if (obj) process.stdout.write(JSON.stringify(obj));
    process.exit(0);
}

// The hook payload ({ stop_hook_active, … }); empty when stdin is not valid JSON.
let payload = {};
try { payload = JSON.parse(fs.readFileSync(0, 'utf8') || '{}'); } catch { payload = {}; }

try {
    const builder = path.join(__dirname, 'build-index.js');
    spawnSync(process.execPath, [builder, '--quiet'], { cwd: ROOT, stdio: 'ignore', timeout: 25000 });

    const gitDir = git('rev-parse', '--absolute-git-dir')?.trim();
    const stateFile = gitDir ? path.join(gitDir, 'claude-doc-check') : null;
    const now = fingerprint();
    let last = null;
    try { last = stateFile ? fs.readFileSync(stateFile, 'utf8') : null; } catch { last = null; }
    if (now && now === last) reply();

    // Records this working tree as checked, so an unchanged next turn exits at once.
    const remember = () => { if (stateFile && now) { try { fs.writeFileSync(stateFile, now); } catch { /* ignore */ } } };
    const check = spawnSync(process.execPath, [builder, '--check', '--quiet'], { cwd: ROOT, encoding: 'utf8', timeout: 25000 });
    const report = `${check.stdout ?? ''}${check.stderr ?? ''}`.trim();

    if (check.status === 0) { remember(); reply(); }
    if (payload.stop_hook_active) {
        remember();
        reply({ systemMessage: `Doc drift is still there after one fix attempt — please review:\n${report}` });
    }
    reply({
        decision: 'block',
        reason: 'The docs or the code index have drifted from the code. Fix every error below (CLAUDE.md, docs/REFERENCE.md, '
            + `.env.example, READMEs as needed), run \`npm run index:check\`, then finish; if one should not be fixed, say why.\n\n${report}`,
    });
} catch (err) {
    reply({ systemMessage: `stop-hook: could not run the doc check — ${err.message}` });
}
