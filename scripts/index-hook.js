'use strict';

/* ─── About this file ─────────────────────────────────────────────────────────
 * Claude Code PostToolUse hook (.claude/settings.json). After an Edit/Write to
 * an indexed code file or a hand-written doc, rebuilds the generated parts
 * (Contents blocks, CODE_INDEX.md, section lists) so their line numbers match.
 * Regenerates only — drift mid-change is expected; the Stop hook
 * (scripts/stop-hook.js) is what asks for it to be fixed.
 * Reads the hook payload (JSON) from stdin; does nothing for other files and
 * never fails the tool call.
 * ─────────────────────────────────────────────────────────────────────────── */

// ----- Contents (generated by `npm run index` — do not edit) -----
// L23  Hook
// L26    ROOT
// L29    WATCHED
// L32    editedFile()
// ----- end of contents -----

const { spawnSync } = require('child_process');
const path = require('path');

// ─── Hook ─────────────────────────────────────────────────────────────────────

// Project root (the folder above scripts/).
const ROOT = path.join(__dirname, '..');

// Code folders and docs that the builder indexes (mirrors CODE_ROOTS / docs in build-index.js).
const WATCHED = /^(bot\.js|(src|telegram|intent|weekly-report|scripts)\/.+\.(c?js|mjs|md)|docs\/.+\.md|[^/]+\.md)$/;

// Project-relative path of the edited file, or '' when the payload has none.
function editedFile(raw) {
    try {
        const file = JSON.parse(raw).tool_input?.file_path ?? '';
        return file ? path.relative(ROOT, path.resolve(file)).replace(/\\/g, '/') : '';
    } catch {
        return '';
    }
}

// The hook payload, read from stdin in chunks.
let raw = '';
process.stdin.on('data', (c) => { raw += c; });
process.stdin.on('end', () => {
    const file = editedFile(raw);
    if (!WATCHED.test(file) || file === 'CODE_INDEX.md') return;
    // Quiet on success; a parse failure still reaches stderr so a broken index is noticed.
    spawnSync(process.execPath, [path.join(__dirname, 'build-index.js'), '--quiet'], {
        cwd: ROOT, stdio: ['ignore', 'ignore', 'inherit'], timeout: 25000,
    });
});
