// Reads a project file as text, or returns null when it does not exist.
function readText(relPath) {
    try { return fs.readFileSync(path.join(ROOT, relPath), 'utf8'); } catch { return null; }
}

// Walks a folder and returns every file path (project-relative) that passes `keep`.
function walk(relDir, keep) {
    const out = [];
    const abs = path.join(ROOT, relDir);
    if (!fs.existsSync(abs)) return out;
    if (fs.statSync(abs).isFile()) return keep(relDir) ? [relDir] : [];
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
        if (entry.isDirectory()) {
            if (SKIP_DIRS.has(entry.name)) continue;
            out.push(...walk(`${relDir}/${entry.name}`.replace(/^\.\//, ''), keep));
        } else if (keep(`${relDir}/${entry.name}`.replace(/^\.\//, ''))) {
            out.push(`${relDir}/${entry.name}`.replace(/^\.\//, ''));
        }
    }
    return out;
}

// Every indexed code file, sorted.
function listCodeFiles() {
    const files = [];
    for (const r of CODE_ROOTS) files.push(...walk(r, f => /\.(c?js|mjs)$/.test(f)));
    return [...new Set(files)].sort();
}

// Every hand-written doc (generated CODE_INDEX.md excluded), sorted.
function listDocFiles() {
    const files = fs.readdirSync(ROOT).filter(f => f.endsWith('.md') && f !== INDEX_FILE);
    for (const d of DOC_DIRS) files.push(...walk(d, f => f.endsWith('.md')));
    for (const r of CODE_ROOTS) files.push(...walk(r, f => /(^|\/)README\.md$/.test(f)));
    files.push(...walk('intent', f => f.endsWith('.md')));
    return [...new Set(files)].sort();
}

// Splits text into lines and remembers its line ending and BOM, so a rewrite keeps both.
function splitText(text) {
    const bom = text.charCodeAt(0) === 0xfeff;
    const body = bom ? text.slice(1) : text;
    const eol = body.includes('\r\n') ? '\r\n' : '\n';
    return { bom, eol, lines: body.split(/\r?\n/) };
}

// Joins lines back with the original line ending and BOM.
function joinText({ bom, eol }, lines) {
    return (bom ? '﻿' : '') + lines.join(eol);
}

// Escapes a table cell so a `|` inside it does not split the row.
function cell(text) {
    return String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

// ─── JavaScript scanner ───────────────────────────────────────────────────────
// A small tokenizer: enough to tell code from comments, strings, template text
// and regex literals line by line. It does not parse JavaScript fully.

// Words after which a `/` starts a regex literal rather than a division.
const REGEX_AFTER_WORDS = new Set(['return', 'typeof', 'case', 'do', 'else', 'in', 'of', 'new', 'delete', 'void', 'throw', 'yield', 'await', 'instanceof']);

// Scans JS source. Returns per-line start states, comments, code tokens and a
// "blanked" copy of the source where comments are replaced by spaces (same offsets).
function scanJs(src) {
    const lineStart = ['code'];            // state at the start of each line (index 0 = line 1)
    const comments  = [];                  // { line, endLine, text, kind: 'line' | 'block', col }
    const tokens    = [];                  // { t, line, pos } significant tokens (no whitespace or comments)
    const blank     = src.split('');       // comments overwritten with spaces
    const tplStack  = [];                  // brace depth at each open `${`
    let depth = 0;
    let line  = 1;
    let last  = null;                      // last significant token text
    let i = 0;

    // Aborts the scan with the current line number.
    const fail = (msg) => { throw new Error(`line ${line}: ${msg}`); };
    // Records the state the next line starts in.
    const newline = (state) => { line++; lineStart.push(state); };
    // Whether a `/` here starts a regex literal (judged from the previous token).
    const regexAllowed = () => {
        if (last === null) return true;
        if (/^[\w$]+$/.test(last)) return REGEX_AFTER_WORDS.has(last);
        if (last.startsWith('\'') || last.startsWith('"') || last.startsWith('`') || last.startsWith('/')) return false;
        return !/^[)\]]$/.test(last);
    };
    // Records a significant token.
    const push = (t, pos) => { tokens.push({ t, line, pos }); last = t; };

    // Reads template text from i (just after ` or a closing `}` of ${...}).
    // Returns true when it stopped at `${`, false when the template ended.
    const readTemplate = (startPos) => {
        let startLine = line;
        while (i < src.length) {
            const c = src[i];
            if (c === '\\') { if (src[i + 1] === '\n') newline('template'); i += 2; continue; }
            if (c === '`') { i++; tokens.push({ t: src.slice(startPos, i), line: startLine, pos: startPos }); last = '`'; return false; }
            if (c === '$' && src[i + 1] === '{') {
                i += 2;
                tokens.push({ t: src.slice(startPos, i), line: startLine, pos: startPos });
                last = '{';
                tplStack.push(depth);
                depth++;
                return true;
            }
            if (c === '\n') newline('template');
            i++;
        }
        fail('unterminated template literal');
    };

    while (i < src.length) {
        const c = src[i];
        const d = src[i + 1];
        if (c === '\n') { newline('code'); i++; continue; }
        if (c === ' ' || c === '\t' || c === '\r') { i++; continue; }

        if (c === '/' && d === '/') {
            let j = src.indexOf('\n', i);
            if (j === -1) j = src.length;
            comments.push({ line, endLine: line, text: src.slice(i, j), kind: 'line', col: i - src.lastIndexOf('\n', i - 1) - 1 });
            for (let k = i; k < j; k++) blank[k] = ' ';
            i = j;
            continue;
        }
        if (c === '/' && d === '*') {
            const j = src.indexOf('*/', i + 2);
            if (j === -1) fail('unterminated block comment');
            const startLine = line;
            for (let k = i; k < j + 2; k++) {
                if (src[k] === '\n') newline('block'); else if (src[k] !== '\r') blank[k] = ' ';
            }
            comments.push({ line: startLine, endLine: line, text: src.slice(i, j + 2), kind: 'block', col: i - src.lastIndexOf('\n', i - 1) - 1 });
            i = j + 2;
            continue;
        }
        if (c === '\'' || c === '"') {
            const start = i;
            i++;
            while (i < src.length && src[i] !== c) {
                if (src[i] === '\\') { if (src[i + 1] === '\n') newline('string'); i += 2; continue; }
                if (src[i] === '\n') fail('unterminated string');
                i++;
            }
            if (i >= src.length) fail('unterminated string');
            i++;
            push(src.slice(start, i), start);
            continue;
        }
        if (c === '`') {
            const start = i;
            i++;
            readTemplate(start);
            continue;
        }
        if (c === '/' && regexAllowed()) {
            const start = i;
            let inClass = false;
            i++;
            while (i < src.length) {
                const r = src[i];
                if (r === '\n') fail('unterminated regex');
                if (r === '\\') { i += 2; continue; }
                if (r === '[') inClass = true;
                else if (r === ']') inClass = false;
                else if (r === '/' && !inClass) break;
                i++;
            }
            i++;
            while (/[a-z]/i.test(src[i] || '')) i++;
            push(src.slice(start, i), start);
            continue;
        }
        if (/[\w$]/.test(c)) {
            const start = i;
            while (i < src.length && /[\w$]/.test(src[i])) i++;
            push(src.slice(start, i), start);
            continue;
        }
        if (c === '{') { depth++; push('{', i); i++; continue; }
        if (c === '}') {
            if (tplStack.length && tplStack[tplStack.length - 1] === depth - 1) {
                tplStack.pop();
                depth--;
                const start = i;
                i++;
                readTemplate(start);
                continue;
            }
            depth--;
            push('}', i);
            i++;
            continue;
        }
        push(c, i);
        i++;
    }
    if (tplStack.length) fail('unterminated template expression');
    return { lineStart, comments, tokens, blanked: blank.join('') };
}

// The code with every comment and all whitespace removed — used to prove that
// an edit changed comments only.
function codeFingerprint(src) {
    return scanJs(src).tokens.map(t => t.t).join('\u0001');
}

// ─── Code file analysis ───────────────────────────────────────────────────────

// Definition patterns, tried in order on code lines.
const DEF_PATTERNS = [
    { kind: 'function', re: /^(\s*)(?:return\s+)?(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*\(/ },
    { kind: 'class',    re: /^(\s*)class\s+([A-Za-z_$][\w$]*)/ },
    { kind: 'function', re: /^(\s*)(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?(?:function\b|\([^)]*\)\s*=>|[A-Za-z_$][\w$]*\s*=>)/ },
    { kind: 'constant', re: /^(\s*)(?:const|let|var)\s+([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+|[A-Z]{2,}[0-9]*)\s*=/ },
    { kind: 'variable', re: /^()(?:const|let|var)\s+([a-z_$][\w$]*)\s*=(?!\s*require\()/ },
];

// Section header styles: "// ─── Name ───", and a box of rule / "// NAME" / rule.
const HEADER_RE   =/^(\s*)\/\/\s*─{2,}\s*([^─\s].*?)\s*─*\s*$/;
const RULE_RE     = /^(\s*)\/\/\s*─{8,}\s*$/;
const BOX_TEXT_RE = /^(\s*)\/\/\s*(\S.*?)\s*$/;

// Text of a comment without its markers, joined into one line.
function commentText(raw) {
    return raw
        .replace(/^\/\*+|\*+\/$/g, '')
        .split('\n')
        .map(l => l.replace(/^\s*(\/\/+|\*+)\s?/, '').trim())
        .filter(Boolean)
        .join(' ')
        .replace(/─{2,}/g, '')
        .trim();
}

// First sentence of a comment, used as a purpose in CODE_INDEX.md.
function firstSentence(text) {
    const s = text.replace(/\s+/g, ' ').trim();
    const m = s.match(/^(.+?[.!?])(\s|$)/);
    const out = m ? m[1] : s;
    return out.length > 220 ? `${out.slice(0, 217)}…` : out;
}

// Removes an existing generated Contents block; returns the remaining lines.
function stripContents(lines) {
    const start = lines.indexOf(CONTENTS_START);
    if (start === -1) return lines;
    const end = lines.indexOf(CONTENTS_END, start);
    if (end === -1) throw new Error('Contents block has a start marker but no end marker');
    const after = lines[end + 1] === '' ? end + 2 : end + 1;
    return [...lines.slice(0, start), ...lines.slice(after)];
}

// Analyses one code file (with any old Contents block removed).
function analyzeCode(file, text) {
    const meta  = splitText(text);
    const lines = stripContents(meta.lines);
    const src   = lines.join('\n');
    const scan  = scanJs(src);
    // Line n starts outside comments and strings; the set of lines holding code tokens.
    const isCode    = (n) =>scan.lineStart[n - 1] === 'code';
    const codeLines = new Set(scan.tokens.map(t => t.line));

    // Comment lookup by line.
    const commentAt = new Map();
    for (const c of scan.comments) {
        for (let l = c.line; l <= c.endLine; l++) {
            if (!commentAt.has(l)) commentAt.set(l, []);
            commentAt.get(l).push(c);
        }
    }
    // Line n holds a comment and no code.
    const isCommentOnly = (n) => !codeLines.has(n) && commentAt.has(n);

    // Indentation unit (2 or 4 spaces).
    const indents = lines.filter((l, i) => isCode(i + 1) && /^ +\S/.test(l)).map(l => l.match(/^ */)[0].length);
    const unit = indents.length && Math.min(...indents) <= 2 ? 2 : 4;

    // Section headers: "// ─── Name ───" or a three-line box (rule / text / rule).
    const headers = [];
    const headerLines = new Set();
    for (let n = 1; n <= lines.length; n++) {
        const l = lines[n - 1];
        if (!isCode(n) || !isCommentOnly(n)) continue;
        if (RULE_RE.test(l) && RULE_RE.test(lines[n + 1] || '') && BOX_TEXT_RE.test(lines[n] || '')) {
            const [, ind, name] = lines[n].match(BOX_TEXT_RE);
            headers.push({ line: n + 1, indent: ind.length, name });
            headerLines.add(n); headerLines.add(n + 1); headerLines.add(n + 2);
            n += 2;
            continue;
        }
        const m = l.match(HEADER_RE);
        if (m) {
            headers.push({ line: n, indent: m[1].length, name: m[2] });
            headerLines.add(n);
        }
    }

    // File header: the first comment after an optional shebang / 'use strict'.
    let p = 0;
    if (/^#!/.test(lines[0] || '')) p = 1;
    if (/^['"]use strict['"];?\s*$/.test(lines[p] || '')) p++;
    let q = p;
    while (q < lines.length && lines[q].trim() === '') q++;
    let fileHeader = null;
    let insertAfter = p;                       // Contents goes after this many lines
    const firstComment = scan.comments.find(c => c.line === q + 1);
    if (firstComment && !headerLines.has(q + 1)) {
        let end = firstComment.endLine;
        if (firstComment.kind === 'line') {
            while (isCommentOnly(end + 1) && !headerLines.has(end + 1)) end++;
        }
        const followedByBlank = (lines[end] ?? '').trim() === '';
        if (firstComment.kind === 'block' || followedByBlank) {
            const raw = scan.comments.filter(c => c.line >= q + 1 && c.endLine <= end).map(c => c.text).join('\n');
            fileHeader = { start: q + 1, end, text: commentText(raw).replace(/^About this file\s*/, '') };
            insertAfter = end;
        }
    }

    // Purpose comment directly above line n (one blank line allowed), or a trailing comment on it.
    const purposeAbove = (n) => {
        const own = (commentAt.get(n) || []).find(c => c.kind === 'line' && codeLines.has(n));
        let j = n - 1;
        if (j >= 1 && lines[j - 1].trim() === '' && isCommentOnly(j - 1)) j--;
        const block = [];
        while (j >= 1 && isCommentOnly(j) && !headerLines.has(j) && !(fileHeader && j <= fileHeader.end && j >= fileHeader.start)) {
            block.unshift(j);
            j--;
        }
        if (block.length) {
            const raw = scan.comments.filter(c => c.line >= block[0] && c.endLine <= block[block.length - 1]).map(c => c.text).join('\n');
            const t = commentText(raw);
            if (t) return t;
        }
        return own ? commentText(own.text) : null;
    };

    // Definitions: top level, and one level inside top-level functions.
    const defs = [];
    // The definition starting on line n, or null.
    const matchDef = (n) => {
        const l = lines[n - 1];
        for (const { kind, re } of DEF_PATTERNS) {
            const m = l.match(re);
            if (m) return { kind, indent: m[1].length, name: m[2], returned: /^\s*return\s/.test(l) };
        }
        return null;
    };
    // Last line of the definition starting at n (closing brace at the same indent).
    const blockEnd = (n, indent) => {
        const toks = scan.tokens.filter(t => t.line === n);
        let bal = 0, opened = false;
        for (const t of toks) {
            if (t.t === '{') { bal++; opened = true; continue; }
            if (t.t === '}') { bal--; continue; }
            // Template pieces: "`…${" opens an expression, "}…`" closes one, "}…${" does both.
            if (t.t[0] === '`' || t.t[0] === '}') {
                if (t.t[0] === '}') bal--;
                if (t.t.endsWith('${')) { bal++; opened = true; }
            }
        }
        if (opened && bal <= 0) return n;
        if (!opened && !/[{([]\s*$/.test(lines[n - 1])) return n;
        // A line starting with a closing bracket at the same indent ("}", "});", "].join(…);") —
        // but not "}) {", which closes a multi-line parameter list and opens the body.
        const close = new RegExp(`^ {${indent}}[}\\])](?!.*\\{\\s*$)`);
        for (let k = n + 1; k <= lines.length; k++) {
            if (isCode(k) && close.test(lines[k - 1])) return k;
        }
        return n;
    };

    for (let n = 1; n <= lines.length; n++) {
        if (!isCode(n) || !codeLines.has(n)) continue;
        const m = matchDef(n);
        if (!m || m.indent !== 0) continue;
        const end = blockEnd(n, 0);
        const def = { file, line: n, end, indent: 0, name: m.name, kind: m.kind, parent: null };
        defs.push(def);
        if (m.kind === 'function' && end > n) {
            for (let k = n + 1; k < end; k++) {
                if (!isCode(k) || !codeLines.has(k)) continue;
                const c = matchDef(k);
                if (!c || c.indent !== unit || c.kind === 'variable') continue;
                const cEnd = blockEnd(k, c.indent);
                defs.push({ file, line: k, end: cEnd, indent: c.indent, name: c.name, kind: c.kind, parent: def.name, returned: c.returned });
                k = Math.max(k, cEnd);
            }
        }
        n = Math.max(n, end);
    }

    // Purpose for each definition; a run of one-line declarations may share one comment.
    for (const d of defs) {
        d.purpose = purposeAbove(d.line);
        if (!d.purpose) {
            // Walk up through directly adjacent declarations to the first one in the run.
            let top = d.line;
            while (top > 1 && !isCommentOnly(top - 1) && codeLines.has(top - 1) && matchDef(top - 1)?.indent === d.indent) top--;
            if (top !== d.line) d.purpose = purposeAbove(top);
        }
        d.section = [...headers].reverse().find(h => h.line < d.line && h.indent <= d.indent)?.name ?? null;
    }

    // Settings read from the environment.
    const settings = [];
    // Line number of a character offset; `b` is the source with comments blanked out.
    const lineOf = (pos) => src.slice(0, pos).split('\n').length;
    const b = scan.blanked;
    for (const m of b.matchAll(/process\.env\.([A-Z][A-Z0-9_]*)/g)) settings.push({ name: m[1], file, line: lineOf(m.index) });
    for (const m of b.matchAll(/process\.env\[\s*['"]([A-Z0-9_]+)['"]\s*\]/g)) settings.push({ name: m[1], file, line: lineOf(m.index) });
    for (const m of b.matchAll(/(?:const|let|var)\s*\{([^}]*)\}\s*=\s*process\.env\b/g)) {
        for (const part of m[1].split(',')) {
            const name = part.split(/[:=]/)[0].trim();
            if (/^[A-Z][A-Z0-9_]*$/.test(name)) settings.push({ name, file, line: lineOf(m.index + m[0].indexOf(name)) });
        }
    }

    // Events, scheduled jobs and commands.
    const events = [];
    for (const m of b.matchAll(/([A-Za-z_$][\w$]*)\.(on|once)\(\s*['"]([\w:-]+)['"]/g)) {
        events.push({ receiver: m[1], method: m[2], name: m[3], file, line: lineOf(m.index) });
    }
    const jobs = [];
    for (const m of b.matchAll(/cron\.schedule\(\s*['"]([^'"]+)['"]/g)) {
        const n = lineOf(m.index);
        jobs.push({ schedule: m[1], file, line: n, purpose: purposeAbove(n) });
    }
    const commands = [];
    if (/^src\/slash-commands\.js$/.test(file)) {
        const start = lines.findIndex(l => /^const COMMANDS\s*=\s*\[/.test(l));
        const end   = lines.findIndex((l, k) => k > start && /^\];/.test(l));
        if (start !== -1 && end !== -1) {
            const named = [];
            for (let k = start + 1; k < end; k++) {
                const m = lines[k].match(/^(\s*)name:\s*'([a-z0-9-]+)'/);
                if (m && isCode(k + 1)) named.push({ indent: m[1].length, name: m[2], line: k + 1 });
            }
            const top = Math.min(...named.map(x => x.indent));
            for (const x of named.filter(x => x.indent === top)) commands.push({ kind: 'slash', name: `/${x.name}`, file, line: x.line, registered: true });
        }
        for (const m of b.matchAll(/\bcmd\s*===\s*'([a-z0-9-]+)'/g)) commands.push({ kind: 'slash', name: `/${m[1]}`, file, line: lineOf(m.index), handled: true });
    }
    for (const m of b.matchAll(/startsWith\(\s*'(![a-z0-9-]+)'/g)) commands.push({ kind: 'text', name: m[1], file, line: lineOf(m.index), handled: true });
    if (file.startsWith('telegram/')) {
        for (const m of b.matchAll(/(?:startsWith\(\s*|===\s*)'(\/[a-z][a-z0-9_]*)/g)) commands.push({ kind: 'telegram', name: m[1], file, line: lineOf(m.index), handled: true });
    }

    // Imports bound by require(), and names this file exports.
    const requires = [];
    for (const m of b.matchAll(/(?:const|let|var)\s+(\{[^}]*\}|[A-Za-z_$][\w$]*)\s*=\s*require\(\s*['"]([^'"]+)['"]\s*\)/g)) {
        const names = m[1].startsWith('{')
            ? m[1].slice(1, -1).split(',').map(s => s.split(':').pop().trim()).filter(Boolean)
            : [m[1]];
        for (const name of names) requires.push({ name, from: m[2], line: lineOf(m.index), start: m.index, end: m.index + m[0].length });
    }
    const exportsMatch = b.match(/^module\.exports\s*=\s*\{([\s\S]*?)\}/m);   // line start, so a string in a test fixture isn't read as this file's exports
    const exported = new Set(exportsMatch ? exportsMatch[1].split(',').map(s => s.split(':')[0].trim()).filter(Boolean) : []);

    return { file, meta, lines, scan, unit, headers, fileHeader, insertAfter, defs, settings, events, jobs, commands, requires, exported, codeLines };
}

// ─── Contents block ───────────────────────────────────────────────────────────

// Builds the new file text with an up-to-date Contents block.
function renderContents(a) {
    const entries = [
        ...a.headers.map(h => ({ line: h.line, depth: (h.indent / a.unit) * 2, label: h.name })),
        ...a.defs.filter(d => d.kind !== 'variable').map(d => ({
            line:  d.line,
            depth: (d.indent / a.unit) * 2 + 2,
            label: d.kind === 'function' ? `${d.name}()` : d.kind === 'class' ? `class ${d.name}` : d.name,
        })),
    ].sort((x, y) => x.line - y.line || x.depth - y.depth);
    if (entries.length === 0) return joinText(a.meta, a.lines);

    const before = a.lines.slice(0, a.insertAfter);
    const after  = a.lines.slice(a.insertAfter);
    const lead   = before.length && before[before.length - 1].trim() !== '' ? [''] : [];
    const rest   = after[0]?.trim() === '' ? after.slice(1) : after;  // the block brings its own trailing blank
    // Net lines added: lead blank + start + entries + end + trailing blank, minus a blank line replaced.
    const blockSize = lead.length + entries.length + 3 - (after.length - rest.length);
    const width = String(Math.max(...entries.map(e => e.line)) + blockSize).length + 1;
    const body = entries.map(e => {
        const n = e.line > a.insertAfter ? e.line + blockSize : e.line;
        return `// L${String(n).padEnd(width)} ${' '.repeat(e.depth)}${e.label}`.trimEnd();
    });
    const out = [...before, ...lead, CONTENTS_START, ...body, CONTENTS_END, '', ...rest];
    return joinText(a.meta, out);
}

// ─── Docs ─────────────────────────────────────────────────────────────────────

// Headings of a Markdown file (fenced code ignored): { line, level, text }.
function mdHeadings(lines) {
    const out = [];
    let fence = null;
    lines.forEach((l, i) => {
        const f = l.match(/^\s*(```|~~~)/);
        if (f) { fence = fence === f[1] ? null : (fence ?? f[1]); return; }
        if (fence) return;
        const m = l.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
        if (m) out.push({ line: i + 1, level: m[1].length, text: m[2] });
    });
    return out;
}

// GitHub's anchor for a heading.
function slug(text) {
    return text.trim().toLowerCase()
        .replace(/[^\p{L}\p{N}\s_-]/gu, '')
        .replace(/ /g, '-');
}

// All anchors of a Markdown file, with GitHub's "-1", "-2" suffixes for repeats.
function anchorsOf(lines) {
    const seen = new Map();
    const out = new Set();
    for (const h of mdHeadings(lines)) {
        const base = slug(h.text.replace(/`/g, ''));
        const count = seen.get(base) ?? 0;
        out.add(count ? `${base}-${count}` : base);
        seen.set(base, count + 1);
    }
    return out;
}

// Removes an existing generated section list; returns the remaining lines.
function stripSections(lines) {
    const start = lines.indexOf(SECTIONS_START);
    if (start === -1) return lines;
    const end = lines.indexOf(SECTIONS_END, start);
    if (end === -1) throw new Error('section list has a start marker but no end marker');
    const after = lines[end + 1] === '' ? end + 2 : end + 1;
    return [...lines.slice(0, start), ...lines.slice(after)];
}

// Builds the new doc text with an up-to-date section list (long docs only).
function renderSections(file, text) {
    const meta  = splitText(text);
    const lines = stripSections(meta.lines);
    const long  = lines.length > LONG_DOC_LINES && !NO_SECTION_LIST.has(file) && !DOC_WRITE_EXCLUDE.has(file);
    const heads = mdHeadings(lines).filter(h => h.level === 2 || h.level === 3);
    if (!long || heads.length === 0) return { text: joinText(meta, lines), lines };

    const at = /^#\s/.test(lines[0] || '') ? 1 : 0;              // after the H1 title
    const lead = at ? [''] : [];
    const rest = lines.slice(at);
    const restTrim = rest[0]?.trim() === '' ? rest.slice(1) : rest;   // the block brings its own trailing blank
    // Net lines added: lead blank + start + headings + end + trailing blank, minus a blank line replaced.
    const blockSize = lead.length + heads.length + 3 - (rest.length - restTrim.length);
    const width = String(Math.max(...heads.map(h => h.line)) + blockSize).length + 1;
    // "<!--" / "-->" inside a heading would end the HTML comment early, so they are shortened.
    const safe = (s) => s.replace(/<!--/g, '<!-').replace(/-->/g, '->');
    const body = heads.map(h => `L${String(h.line > at ? h.line + blockSize : h.line).padEnd(width)} ${h.level === 3 ? '  ' : ''}${safe(h.text)}`);
    const out = [...lines.slice(0, at), ...lead, SECTIONS_START, ...body, SECTIONS_END, '', ...restTrim];
    return { text: joinText(meta, out), lines: out };
}

// Rows of the first Markdown table under a `## Heading` (matched by prefix): arrays of cells.
function tableUnder(lines, headingPrefix) {
    const heads = mdHeadings(lines);
    const h = heads.find(x => x.text.toLowerCase().startsWith(headingPrefix.toLowerCase()));
    if (!h) return null;
    const next = heads.find(x => x.line > h.line && x.level <= h.level);
    const stop = next ? next.line - 1 : lines.length;
    const rows = [];
    for (let k = h.line; k < stop; k++) {
        const l = lines[k];
        if (!/^\s*\|/.test(l)) { if (rows.length) break; continue; }
        if (/^\s*\|[\s:|-]+\|\s*$/.test(l)) continue;
        rows.push({ line: k + 1, cells: l.trim().replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map(s => s.replace(/\\\|/g, '|').trim()) });
    }
    return rows.slice(1);                                          // drop the header row
}

// Backticked spans in a string.
function ticks(s) {
    return [...String(s).matchAll(/`([^`]+)`/g)].map(m => m[1]);
}

