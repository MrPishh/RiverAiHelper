// ─── Drift checks ─────────────────────────────────────────────────────────────

// Runs every drift check. Returns { errors: string[], warnings: string[] }.
function runChecks(ctx) {
    const { all, docs, codeFiles, settingsInfo, commandsInfo, eventsAll, scripts } = ctx;
    const errors = [];
    const warnings = [];
    // Records an error (or a warning, for a known finding listed in KNOWN_FINDINGS).
    const err  = (check, msg, file = '', name = '') => {
        const known = KNOWN_FINDINGS.get(`${check}|${file}|${name}`);
        if (known) warnings.push(`[${check}] ${msg} (known: ${known})`);
        else errors.push(`[${check}] ${msg}`);
    };
    // Records a warning; docLines(f) gives the analysed lines of a doc.
    const warn = (check, msg) => warnings.push(`[${check}] ${msg}`);
    const docLines = (f) => docs.get(f)?.lines ?? null;

    // Words that appear in the code (comments excluded).
    const codeWords = new Set();
    for (const a of all) for (const m of a.scan.blanked.matchAll(/[A-Za-z_$][\w$]*/g)) codeWords.add(m[0]);
    const defIndex = new Map();
    for (const a of all) for (const d of a.defs) {
        if (!defIndex.has(d.name)) defIndex.set(d.name, []);
        defIndex.get(d.name).push(a.file);
    }

    // 1. File map complete.
    const claude = docLines(CLAUDE_DOC);
    const mapRows = claude && tableUnder(claude, 'File map');
    if (!mapRows) err('file map', `${CLAUDE_DOC} has no "## File map" table`);
    else {
        const listed = new Set();
        for (const r of mapRows) {
            for (const t of ticks(r.cells[0])) {
                const p = t.replace(/\/$/, '');
                listed.add(p);
                if (!fs.existsSync(path.join(ROOT, p))) err('file map', `${CLAUDE_DOC}:${r.line} lists \`${t}\`, which does not exist`);
            }
        }
        for (const f of codeFiles) if (!listed.has(f)) err('file map', `\`${f}\` has no row in ${CLAUDE_DOC} § File map`);
    }

    // 2. Task table accurate.
    const taskRows = claude && tableUnder(claude, 'Where to look');
    if (!taskRows) err('task table', `${CLAUDE_DOC} has no "## Where to look for…" table`);
    else {
        for (const r of taskRows) {
            const files = ticks(r.cells[1] ?? '').map(t => t.replace(/:.*$/, ''));
            for (const raw of ticks(r.cells[2] ?? '')) {
                const name = raw.replace(/\(.*$/, '').split(/[.›]/).pop().trim();
                const where = defIndex.get(name);
                if (!where) { err('task table', `${CLAUDE_DOC}:${r.line} names \`${raw}\`, which is not defined anywhere`); continue; }
                if (!where.some(f => files.includes(f))) err('task table', `${CLAUDE_DOC}:${r.line} names \`${raw}\` under ${files.join(', ') || '(no file)'}, but it is defined in ${[...new Set(where)].join(', ')}`);
            }
        }
    }

    // 3. Code names in CLAUDE.md and README.md exist in the code.
    for (const f of NAME_CHECK_DOCS) {
        const lines = docLines(f);
        if (!lines) continue;
        let fence = false;
        lines.forEach((l, i) => {
            if (/^\s*(```|~~~)/.test(l)) { fence = !fence; return; }
            if (fence) return;
            for (const raw of ticks(l)) {
                if (/[\s/'"<>#=]/.test(raw.replace(/\(.*\)$/, '')) || /^[!/]/.test(raw)) continue;
                let name = raw.replace(/\(.*$/, '');
                if (name.includes('.')) name = name.split('.').pop();
                const looksLikeCode = /^[a-z][a-z0-9]*[A-Z][A-Za-z0-9]*$/.test(name)
                    || /^[a-z][a-z0-9]*_[a-z0-9_]+$/.test(name)
                    || /^[A-Z][A-Z0-9]*_[A-Z0-9_]+$/.test(name)
                    || /\(.*\)$/.test(raw);
                if (looksLikeCode && /^[A-Za-z_$][\w$]*$/.test(name) && !codeWords.has(name)) {
                    err('code names', `${f}:${i + 1} mentions \`${raw}\`, which does not appear in the code`);
                }
            }
        });
    }

    // 4. Settings in step: code ↔ .env.example ↔ .env (names only) ↔ docs table.
    const code = new Set(settingsInfo.byName.keys());
    const example = settingsInfo.example;
    const local = settingsInfo.local;
    const refRows = docLines(REFERENCE_DOC) && tableUnder(docLines(REFERENCE_DOC), 'Settings');
    const documented = new Set((refRows ?? []).flatMap(r => ticks(r.cells[0])).filter(t => /^[A-Z][A-Z0-9_]*$/.test(t)));
    if (!refRows) err('settings', `${REFERENCE_DOC} has no "## Settings" table`);
    for (const n of code) {
        if (!example.has(n))    err('settings', `\`${n}\` is read by the code but missing from .env.example`);
        if (refRows && !documented.has(n)) err('settings', `\`${n}\` is read by the code but missing from ${REFERENCE_DOC} § Settings`);
        if (local && !local.has(n)) warn('settings', `\`${n}\` is read by the code but not set in your local .env`);
    }
    for (const n of example) if (!code.has(n)) err('settings', `\`${n}\` is in .env.example but the code never reads it`);
    for (const n of documented) if (!code.has(n)) err('settings', `\`${n}\` is documented in ${REFERENCE_DOC} but the code never reads it`);
    if (local) for (const n of local) if (!code.has(n)) warn('settings', `\`${n}\` is set in your local .env but the code never reads it`);

    // 5. Commands and events in step with docs/REFERENCE.md.
    const ref = docLines(REFERENCE_DOC);
    const cmdRows = ref && tableUnder(ref, 'Commands');
    if (!cmdRows) err('commands', `${REFERENCE_DOC} has no "## Commands" table`);
    else {
        const docCmds = new Map();
        for (const r of cmdRows) {
            const m = (ticks(r.cells[0])[0] ?? '').match(/^([!/][a-z0-9_-]+)/);
            if (m) docCmds.set(m[1], r.line);
        }
        for (const c of commandsInfo) if (!docCmds.has(c.name)) err('commands', `\`${c.name}\` (${c.kind}) is defined in the code but missing from ${REFERENCE_DOC} § Commands`);
        const known = new Set(commandsInfo.map(c => c.name));
        for (const [name, line] of docCmds) if (!known.has(name)) err('commands', `${REFERENCE_DOC}:${line} documents \`${name}\`, which the code does not define`);
        for (const c of commandsInfo) if (c.kind === 'slash' && c.registered && c.handled.length === 0) err('commands', `\`${c.name}\` is registered with Discord but has no handler`);
    }
    const evRows = ref && tableUnder(ref, 'Events');
    if (!evRows) err('events', `${REFERENCE_DOC} has no "## Events" table`);
    else {
        const docEv = new Set(evRows.flatMap(r => ticks(r.cells[0])));
        const codeEv = new Set(eventsAll.map(e => `${e.receiver}.${e.name}`));
        for (const e of codeEv) if (!docEv.has(e)) err('events', `\`${e}\` is handled in the code but missing from ${REFERENCE_DOC} § Events`);
        for (const e of docEv) if (/^[\w$]+\.[\w:-]+$/.test(e) && !codeEv.has(e)) err('events', `${REFERENCE_DOC} documents \`${e}\`, which the code does not handle`);
    }

    // 6. Task-runner commands in step.
    const mentioned = new Map();
    for (const [f, d] of docs) {
        let generated = false;
        d.lines.forEach((l, i) => {
            if (l === SECTIONS_START) { generated = true; return; }
            if (generated) { if (l === SECTIONS_END) generated = false; return; }
            for (const m of l.matchAll(/\bnpm\s+(?:run\s+([a-z][\w:-]*)|(start|test|stop|restart)\b)/g)) {
                const name = m[1] ?? m[2];
                if (NPM_BUILTINS.has(name)) continue;
                if (!mentioned.has(name)) mentioned.set(name, `${f}:${i + 1}`);
            }
        });
    }
    for (const [name, where] of mentioned) if (!(name in scripts)) err('npm scripts', `${where} mentions \`npm run ${name}\`, which package.json does not define`);
    for (const name of Object.keys(scripts)) {
        if (/^(pre|post)/.test(name)) continue;
        if (!mentioned.has(name)) err('npm scripts', `\`npm run ${name}\` is in package.json but no doc mentions it`);
    }

    // 7. No hand-written line numbers in docs.
    for (const [f, d] of docs) {
        let fence = false, generated = false;
        d.lines.forEach((l, i) => {
            if (l === SECTIONS_START) { generated = true; return; }
            if (generated) { if (l === SECTIONS_END) generated = false; return; }
            if (/^\s*(```|~~~)/.test(l)) { fence = !fence; return; }
            if (fence) return;
            const hit = l.match(/\b[\w./-]+\.(?:c?js|mjs|json|md|ts|py):\d+/) || l.match(/\blines?\s+\d+(?:\s*(?:[–-]|to)\s*\d+)?\b/i) || l.match(/~\s*line\s*\d+/i);
            if (hit) err('line numbers', `${f}:${i + 1} has a hand-written line number ("${hit[0]}") — point to a heading or a name instead`);
        });
    }

    // 8. Links resolve.
    for (const [f, d] of docs) {
        let fence = false;
        d.lines.forEach((l, i) => {
            if (/^\s*(```|~~~)/.test(l)) { fence = !fence; return; }
            if (fence) return;
            for (const m of l.replace(/`[^`]*`/g, '').matchAll(/\[[^\]]*\]\(([^)\s]+)\)/g)) {
                const target = m[1];
                if (/^(https?:|mailto:|tg:)/.test(target)) continue;
                const [p, anchor] = target.split('#');
                const destRel = p ? path.posix.normalize(path.posix.join(path.posix.dirname(f), decodeURIComponent(p))) : f;
                if (p && !fs.existsSync(path.join(ROOT, destRel))) { err('links', `${f}:${i + 1} links to \`${target}\`, which does not exist`); continue; }
                if (anchor && destRel.endsWith('.md')) {
                    const destLines = docs.get(destRel)?.lines ?? (readText(destRel) ?? '').split(/\r?\n/);
                    if (!anchorsOf(destLines).has(anchor)) err('links', `${f}:${i + 1} links to \`${target}\`, but ${destRel} has no heading with that anchor`);
                }
            }
        });
    }

    // 9. No dead code: unused imports and private definitions used nowhere.
    for (const a of all) {
        const ids = a.scan.tokens.filter(t => /^[A-Za-z_$][\w$]*$/.test(t.t));
        for (const r of a.requires) {
            const used = ids.some(t => t.t === r.name && (t.pos < r.start || t.pos >= r.end));
            if (!used) err('dead code', `${a.file}:${r.newLine} imports \`${r.name}\` but never uses it`, a.file, r.name);
        }
        for (const d of a.defs) {
            if (a.exported.has(d.name) || d.returned) continue;
            const uses = ids.filter(t => t.t === d.name && t.line !== d.line).length;
            if (uses === 0) err('dead code', `${a.file}:${d.newLine} defines \`${d.name}\` but nothing uses it`, a.file, d.name);
        }
    }

    // Warnings: missing purpose comments, definitions outside any section, exports nobody uses.
    for (const a of all) {
        for (const d of a.defs) {
            if (!d.purpose) warn('purpose', `${a.file}:${d.newLine} \`${d.name}\` has no purpose comment`);
            if (!d.section && d.indent === 0 && a.headers.length) warn('sections', `${a.file}:${d.newLine} \`${d.name}\` is outside any section`);
        }
        if (!a.fileHeader) warn('purpose', `${a.file} has no file header comment`);
    }
    // True when another indexed file uses `name`.
    const usedElsewhere =(name, file) => all.some(o => o.file !== file && o.scan.tokens.some(t => t.t === name));
    for (const a of all) for (const name of a.exported) if (!usedElsewhere(name, a.file)) warn('exports', `${a.file} exports \`${name}\`, which no other file uses`);

    return { errors, warnings };
}

