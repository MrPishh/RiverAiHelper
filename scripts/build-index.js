        out.push(`| \`${c.name}\` | ${c.kind} | ${c.registered ? loc(c.registered.file, c.registered.newLine) : c.kind === 'slash' ? '**not registered**' : '—'} | ${c.handled.map(h => loc(h.file, h.newLine)).join(', ') || '—'} |`);
