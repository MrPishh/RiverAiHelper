// Names in a .env-style file (values are never read into the report).
function envNames(relPath) {
    const text = readText(relPath);
    if (text === null) return null;
    return new Set(text.split(/\r?\n/).map(l => l.match(/^\s*([A-Z][A-Z0-9_]*)\s*=/)?.[1]).filter(Boolean));
}

// Works out every generated file and the drift report. Writes nothing.
function build() {
    const codeFiles = listCodeFiles();
    const outputs = new Map();                                     // relPath → desired text
    const all = [];
    const failures = [];

    for (const f of codeFiles) {
        const text = readText(f);
        try {
            const a = analyzeCode(f, text);
            const newText = renderContents(a);
            outputs.set(f, newText);
            // Map each line in the analysed text to its line in the rendered file.
            const shift = (newText.split(/\r?\n/).length - a.lines.length);
            const map = (n) => (n > a.insertAfter && shift > 0 ? n + shift : n);
            for (const d of a.defs) d.newLine = map(d.line);
            for (const x of [...a.settings, ...a.events, ...a.jobs, ...a.commands, ...a.requires]) x.newLine = map(x.line);
            a.renderedLines = newText.split(/\r?\n/).length - (newText.endsWith('\n') ? 1 : 0);
            all.push(a);
        } catch (e) {
            failures.push(`${f}: ${e.message}`);
        }
    }

    const docs = new Map();
    for (const f of listDocFiles()) {
        const text = readText(f);
        try {
            const r = renderSections(f, text);
            if (!DOC_WRITE_EXCLUDE.has(f)) outputs.set(f, r.text);
            docs.set(f, { lines: r.lines });
        } catch (e) {
            failures.push(`${f}: ${e.message}`);
        }
    }
    if (failures.length) return { failures };

    // Settings, commands and events across all files.
    const byName = new Map();
    for (const a of all) for (const s of a.settings) {
        if (!byName.has(s.name)) byName.set(s.name, []);
        byName.get(s.name).push(s);
    }
    const settingsInfo = { byName, example: envNames('.env.example') ?? new Set(), local: envNames('.env') };
    const cmdMap = new Map();
    for (const a of all) for (const c of a.commands) {
        if (!cmdMap.has(c.name)) cmdMap.set(c.name, { name: c.name, kind: c.kind, registered: null, handled: [] });
        const e = cmdMap.get(c.name);
        if (c.registered) e.registered = c; else e.handled.push(c);
    }
    const commandsInfo = [...cmdMap.values()].sort((x, y) => x.kind.localeCompare(y.kind) || x.name.localeCompare(y.name));
    const eventsAll = all.flatMap(a => a.events);
    const scripts = JSON.parse(readText('package.json') || '{}').scripts || {};

    outputs.set(INDEX_FILE, renderIndex(all, settingsInfo, commandsInfo, scripts));
    const report = runChecks({ all, docs, codeFiles, settingsInfo, commandsInfo, eventsAll, scripts });
    return { outputs, report, all };
}

// Files whose desired text differs from what is on disk.
function staleFiles(outputs) {
    return [...outputs].filter(([f, text]) => readText(f) !== text).map(([f]) => f);
}

// Prints the drift report; returns true when it has errors.
function printReport({ errors, warnings }, quiet) {
    if (errors.length) {
        console.log(`Doc drift — ${errors.length} error(s):`);
        for (const e of errors) console.log(`  ✗ ${e}`);
    }
    if (!quiet && warnings.length) {
        console.log(`Warnings (${warnings.length}, never failing):`);
        for (const w of warnings) console.log(`  · ${w}`);
    }
    if (!quiet && !errors.length) console.log('Doc drift: none.');
    return errors.length > 0;
}

// Default and --check modes.
function runOnce({ check, quiet }) {
    const result = build();
    if (result.failures) {
        console.error('Index not written — could not parse:');
        for (const f of result.failures) console.error(`  ✗ ${f}`);
        return 2;
    }
    const stale = staleFiles(result.outputs);
    if (check) {
        if (stale.length) {
            console.log(`Stale generated parts (run \`${INDEX_COMMAND}\`):`);
            for (const f of stale) console.log(`  ✗ ${f}`);
        }
        const drift = printReport(result.report, quiet);
        return stale.length || drift ? 1 : 0;
    }
    for (const f of stale) fs.writeFileSync(path.join(ROOT, f), result.outputs.get(f), 'utf8');
    if (!quiet && stale.length) console.log(`Updated: ${stale.join(', ')}`);
    printReport(result.report, quiet);
    return 0;
}

// --watch mode: rebuild after every save in the indexed folders and docs.
function watch() {
    runOnce({ check: false, quiet: false });
    let timer = null;
    // Debounced rebuild after a change.
    const trigger = (name) => {
        if (!name || /CODE_INDEX\.md$/.test(name)) return;
        clearTimeout(timer);
        timer = setTimeout(() => { console.log(`\n— change in ${name} —`); runOnce({ check: false, quiet: false }); }, 300);
    };
    const targets = [...CODE_ROOTS, ...DOC_DIRS, '.'];
    for (const t of targets) {
        const abs = path.join(ROOT, t);
        if (!fs.existsSync(abs)) continue;
        const recursive = t !== '.' && fs.statSync(abs).isDirectory();
        fs.watch(abs, { recursive }, (_, name) => {
            if (t === '.' && !/\.md$/.test(name || '')) return;
            trigger(name);
        });
    }
    console.log('Watching for changes — Ctrl+C to stop.');
}

if (require.main === module) {
    const args = new Set(process.argv.slice(2));
    if (args.has('--watch')) watch();
    else process.exitCode = runOnce({ check: args.has('--check'), quiet: args.has('--quiet') });
}

