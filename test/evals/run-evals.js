const path = require('path');

// ─── Setup ────────────────────────────────────────────────────────────────────

// Project root, settings and the real modules under test.
const ROOT = path.join(__dirname, '..', '..');
require('dotenv').config({ path: path.join(ROOT, '.env'), quiet: true });
const Anthropic = require('@anthropic-ai/sdk');
const state = require(path.join(ROOT, 'src', 'state'));
const { createIntentModule } = require(path.join(ROOT, 'src', 'intent'));
const { createClaudeModule } = require(path.join(ROOT, 'src', 'claude'));
const { searchKB } = require(path.join(ROOT, 'src', 'rag'));
const { getSourceFiles } = require(path.join(ROOT, 'src', 'knowledge-loader'));
const cases = require('./cases.json');

// ─── Runners ──────────────────────────────────────────────────────────────────

// Classifies each intent case and reports matches; returns [passed, total].
async function runIntent(intent) {
    let pass = 0, behaviour = 0;
    console.log('\n── Intent classification ── (⚠ = wrong category AND the bot would answer/ignore wrongly)');
    for (const c of cases.intent) {
        const got = await intent.classifyMessageIntent(c.message, null);
        // `expect` is one category, or a list when the taxonomy allows either.
        const expected = [].concat(c.expect);
        const ok = expected.includes(got);
        // What matters most: does the bot answer when it should, and stay silent when it should?
        const sameAction = intent.RESPOND_INTENTS.has(got) === intent.RESPOND_INTENTS.has(expected[0]);
        if (ok) pass++;
        if (sameAction) behaviour++;
        console.log(`${ok ? '✓' : sameAction ? '✗' : '⚠'} ${expected.join('|').padEnd(22)} ${ok ? '' : `got ${got.padEnd(20)}`} "${c.message.slice(0, 70)}"${!ok && c.why ? `  (${c.why})` : ''}`);
    }
    console.log(`answer/ignore decision correct: ${behaviour}/${cases.intent.length}`);
    return [pass, cases.intent.length];
}

// Answers each question through the real pipeline and checks type and required/forbidden phrases.
async function runAnswers(claude) {
    let pass = 0;
    console.log('\n── Answers ──');
    for (const [i, c] of cases.answers.entries()) {
        let reply = '';
        const target = { reply: async (text) => { reply += text; return { id: `eval-${i}-${Date.now()}` }; } };
        await claude.answerQuestion({ question: c.question, targetMessage: target, userId: `eval-user-${i}`, channelId: 'tg_eval' });
        const lower = reply.toLowerCase();
        const missing = c.mustInclude.filter(any => !any.some(p => lower.includes(p.toLowerCase())));
        const forbidden = c.mustNotInclude.filter(p => lower.includes(p.toLowerCase()));
        const ok = reply && missing.length === 0 && forbidden.length === 0;
        if (ok) pass++;
        console.log(`${ok ? '✓' : '✗'} "${c.question}"`);
        if (!ok) {
            if (missing.length) console.log(`    missing one of: ${missing.map(a => a.join(' / ')).join('; ')}`);
            if (forbidden.length) console.log(`    contains forbidden: ${forbidden.join(', ')}`);
            console.log(`    reply: ${reply.replace(/\s+/g, ' ').slice(0, 300)}`);
        }
    }
    return [pass, cases.answers.length];
}

// ─── Main ─────────────────────────────────────────────────────────────────────

(async () => {
    const which = process.argv[2] || 'all';
    const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
    // The bot's code turns API errors into safe defaults (e.g. "help-seeking"), which would be scored as
    // real answers — so check the API works first and stop with a clear message if it doesn't.
    try {
        await anthropic.messages.create({ model: 'claude-haiku-4-5-20251001', max_tokens: 1, messages: [{ role: 'user', content: 'ok' }] });
    } catch (err) {
        console.error(`Anthropic API unavailable — evals not run: ${err.message.slice(0, 200)}`);
        process.exit(2);
    }
    const noUsage = () => {};
    const results = [];
    if (which === 'all' || which === 'intent') {
        results.push(['intent', ...(await runIntent(createIntentModule(anthropic, { SUPPORT_CHANNEL_ID: 'support', trackUsage: noUsage })))]);
    }
    if (which === 'all' || which === 'answers') {
        const claude = createClaudeModule(anthropic, state, { searchKB, getSourceFiles, trackUsage: noUsage });
        claude.loadCoreFacts();
        results.push(['answers', ...(await runAnswers(claude))]);
    }
    console.log('\n── Score ──');
    for (const [name, p, t] of results) console.log(`${name}: ${p}/${t} (${Math.round((p / t) * 100)}%)`);
    process.exitCode = results.every(([, p, t]) => p === t) ? 0 : 1;
})().catch(err => { console.error('eval failed:', err.message); process.exit(2); });
